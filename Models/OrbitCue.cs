using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Runtime.CompilerServices;
using Avalonia.Threading;
using SLSKDONET.Data.Entities;

namespace SLSKDONET.Models;

/// <summary>
/// Source of a cue point.
/// </summary>
public enum CueSource
{
    Auto,  // Generated by ML/Heuristics
    User   // Manually placed or adjusted by user
}

/// <summary>
/// Professional role/label for a cue point.
/// </summary>
public enum CueRole
{
    Intro,
    KickIn,
    Breakdown,
    Breakdown2,
    Drop,
    Climax,
    Vocals,
    Outro,
    Bridge,
    Build,
    PhraseStart,
    Custom,
    /// <summary>Section marker: where the intro section ends (the track "arrives"). Together with the
    /// Intro cue (or the track start) it bounds the intro region a DJ mixes in over.</summary>
    IntroEnd,
    /// <summary>Section marker: where the outro section starts. From here to the end of the track is
    /// the outro region a DJ mixes out over ([OUT] stays the last usable mix-out point).</summary>
    OutroStart,
    /// <summary>User-confirmed track-level entry point for transitions and DJ preparation.</summary>
    MixIn,
    /// <summary>User-confirmed track-level exit point for transitions and DJ preparation.</summary>
    MixOut,
}

/// <summary>
/// Represents a surgical cue point for DJ preparation.
/// part of the Phase 10 Interactive Cue Ecosystem.
///
/// Raises <see cref="INotifyPropertyChanged.PropertyChanged"/> so editors (Cue Forge's cue list,
/// inspector and pads) update live while a cue is renamed, recoloured, nudged or dragged. A change
/// made off the UI thread is posted to it, so a background mutation can't throw from a bound view.
/// </summary>
public class OrbitCue : INotifyPropertyChanged
{
    public event PropertyChangedEventHandler? PropertyChanged;

    private double _timestamp;
    private string _name = string.Empty;
    private string _color = "#FFFFFF";
    private CueSource _source = CueSource.Auto;
    private double _confidence = 1.0;
    private CueRole _role = CueRole.Custom;
    private int _slotIndex;
    private bool _isLoop;
    private double _loopEndSeconds;

    /// <summary>
    /// Position in seconds.
    /// </summary>
    public double Timestamp
    {
        get => _timestamp;
        set { if (Set(ref _timestamp, value)) { Raise(nameof(TimestampDisplay)); Raise(nameof(WhyHereTooltip)); } }
    }

    /// <summary>
    /// Human-readable name.
    /// </summary>
    public string Name { get => _name; set => Set(ref _name, value ?? string.Empty); }

    /// <summary>
    /// Hex color code for DJ hardware (e.g., #FF0000 for Red/Drop).
    /// </summary>
    public string Color { get => _color; set => Set(ref _color, value ?? "#FFFFFF"); }

    /// <summary>
    /// Whether this was generated by ORBIT or placed by the user.
    /// User cues are NEVER overwritten by auto-analysis.
    /// </summary>
    public CueSource Source
    {
        get => _source;
        set { if (Set(ref _source, value)) { Raise(nameof(WhyHereTooltip)); Raise(nameof(IsAuto)); } }
    }

    /// <summary>
    /// Confidence score (0.0 - 1.0) based on transient alignment.
    /// Low confidence cues are flagged for "Review" in the UI.
    /// </summary>
    public double Confidence
    {
        get => _confidence;
        set { if (Set(ref _confidence, value)) { Raise(nameof(ConfidenceColor)); Raise(nameof(WhyHereTooltip)); } }
    }

    /// <summary>
    /// The structural role of this cue.
    /// </summary>
    public CueRole Role
    {
        get => _role;
        set { if (Set(ref _role, value)) { Raise(nameof(WhyHereTooltip)); Raise(nameof(IsSectionMarker)); } }
    }

    /// <summary>
    /// Optional slot index for hardware mapping (Hot Cue 1-8).
    /// </summary>
    public int SlotIndex
    {
        get => _slotIndex;
        set { if (Set(ref _slotIndex, value)) { Raise(nameof(HasSlot)); Raise(nameof(SlotLabel)); Raise(nameof(KindDisplay)); } }
    }

    /// <summary>
    /// When true, this cue represents a loop. LoopEndSeconds marks the loop out point.
    /// </summary>
    public bool IsLoop { get => _isLoop; set { if (Set(ref _isLoop, value)) Raise(nameof(KindDisplay)); } }

    /// <summary>
    /// Loop end position in seconds. Only meaningful when IsLoop is true.
    /// </summary>
    public double LoopEndSeconds { get => _loopEndSeconds; set => Set(ref _loopEndSeconds, value); }

    /// <summary>
    /// True when this is the specific cue TransitionEngine.OptimizeTransition picked as its
    /// mix-out/mix-in recommendation (Mix transition editor). Set once when the suggestion is
    /// computed and left alone after — it represents what the algorithm originally recommended,
    /// distinct from wherever the live trigger point (Nudge, a different cue click) currently
    /// sits, which a waveform's own playhead/progress marker already shows.
    /// </summary>
    public bool IsSuggested { get; set; }

    private bool Set<T>(ref T field, T value, [CallerMemberName] string? name = null)
    {
        if (EqualityComparer<T>.Default.Equals(field, value)) return false;
        field = value;
        Raise(name!);
        return true;
    }

    private void Raise(string name)
    {
        var handler = PropertyChanged;
        if (handler == null) return;
        if (Dispatcher.UIThread.CheckAccess()) handler(this, new PropertyChangedEventArgs(name));
        else Dispatcher.UIThread.Post(() => handler(this, new PropertyChangedEventArgs(name)));
    }

    // ── Display helpers (derived, not persisted) ───────────────────────────

    public string TimestampDisplay => TimeSpan.FromSeconds(Timestamp).ToString(@"mm\:ss\.ff");
    public bool HasSlot => SlotIndex >= 0;
    public bool IsAuto => Source == CueSource.Auto;
    /// <summary>"Hot A" / "Memory" / "Loop" — the cue's kind as shown in cue lists.</summary>
    public string KindDisplay => IsLoop ? "Loop" : SlotIndex is >= 0 and <= 7 ? $"Hot {SlotLabel}" : "Memory";
    public string SlotLabel => SlotIndex >= 0 ? ((char)('A' + Math.Min(SlotIndex, 7))).ToString() : string.Empty;

    // Confidence colour: green ≥80%, amber ≥50%, red <50%
    public string ConfidenceColor => Confidence >= 0.8 ? "#44DD88" : Confidence >= 0.5 ? "#FF9800" : "#FF5555";

    /// <summary>Read-only mapping from the persisted <see cref="CuePointEntity"/> to this display
    /// model — same shape as CueForgeViewModel's private EntityToOrbitCue, shared here so other
    /// consumers (e.g. MixTransitionViewModel's cue-picker waveforms) that only need to DISPLAY
    /// cues, not edit/persist them, don't have to duplicate the mapping.</summary>
    public static OrbitCue FromEntity(CuePointEntity e) => new()
    {
        Timestamp = e.TimestampInSeconds,
        Name = e.Label,
        Color = e.Color,
        Source = e.IsAutoGenerated ? CueSource.Auto : CueSource.User,
        Role = RoleFromType(e.Type),
        Confidence = e.Confidence,
        IsLoop = e.IsLoop,
        LoopEndSeconds = e.LoopEndSeconds,
        SlotIndex = e.SlotIndex,
    };

    /// <summary>Inverse of <see cref="FromEntity"/> — the persisted shape both cue editors (Cue Forge
    /// and the Flow Builder transition editor) write back.</summary>
    public CuePointEntity ToEntity(string trackHash) => new()
    {
        Id = Guid.NewGuid(),
        TrackUniqueHash = trackHash,
        TimestampInSeconds = Timestamp,
        Label = Name,
        Color = Color,
        IsAutoGenerated = Source == CueSource.Auto,
        Type = TypeFromRole(Role),
        Confidence = (float)Confidence,
        IsLoop = IsLoop,
        LoopEndSeconds = LoopEndSeconds,
        SlotIndex = SlotIndex,
        CreatedAt = DateTime.UtcNow,
    };

    /// <summary>Stored cue type → editing role (the one mapping every cue editor uses).</summary>
    public static CueRole RoleFromType(CuePointType type) => type switch
    {
        CuePointType.Intro => CueRole.Intro,
        CuePointType.Outro => CueRole.Outro,
        CuePointType.Drop => CueRole.Drop,
        CuePointType.Breakdown => CueRole.Breakdown,
        CuePointType.Build => CueRole.Build,
        CuePointType.PhraseBoundary => CueRole.PhraseStart,
        CuePointType.IntroEnd => CueRole.IntroEnd,
        CuePointType.OutroStart => CueRole.OutroStart,
        CuePointType.MixIn => CueRole.MixIn,
        CuePointType.MixOut => CueRole.MixOut,
        _ => CueRole.Custom,
    };

    /// <summary>Editing role → stored cue type (inverse of <see cref="RoleFromType"/>; roles the
    /// table has no type for are stored as phrase boundaries, as before).</summary>
    public static CuePointType TypeFromRole(CueRole role) => role switch
    {
        CueRole.Intro => CuePointType.Intro,
        CueRole.Outro => CuePointType.Outro,
        CueRole.Drop => CuePointType.Drop,
        CueRole.Breakdown or CueRole.Breakdown2 => CuePointType.Breakdown,
        CueRole.Build => CuePointType.Build,
        CueRole.IntroEnd => CuePointType.IntroEnd,
        CueRole.OutroStart => CuePointType.OutroStart,
        CueRole.MixIn => CuePointType.MixIn,
        CueRole.MixOut => CuePointType.MixOut,
        _ => CuePointType.PhraseBoundary,
    };

    /// <summary>True for the intro-end / outro-start section markers.</summary>
    public bool IsSectionMarker => Role is CueRole.IntroEnd or CueRole.OutroStart;
    /// <summary>Explicit mix cues plus legacy generated labels, for the focused Flow Builder view.</summary>
    public bool IsMixPoint => Role is CueRole.MixIn or CueRole.MixOut ||
        Name.StartsWith("Mix-In", StringComparison.OrdinalIgnoreCase) ||
        Name.StartsWith("Mix In", StringComparison.OrdinalIgnoreCase) ||
        Name.StartsWith("Mix-Out", StringComparison.OrdinalIgnoreCase) ||
        Name.StartsWith("Mix Out", StringComparison.OrdinalIgnoreCase);

    /// <summary>Field-for-field copy — undo snapshots need cues that later edits can't mutate.</summary>
    public OrbitCue Clone()
    {
        var copy = (OrbitCue)MemberwiseClone();
        copy.PropertyChanged = null; // a copy must not notify the original's subscribers
        return copy;
    }

    // "Why here?" one-liner shown as tooltip on the confidence dot
    public string WhyHereTooltip
    {
        get
        {
            string src = Source == CueSource.User ? "User cue" : $"Auto — {Role}";
            string conf = Source == CueSource.Auto ? $" ({(int)(Confidence * 100)}% confidence)" : "";
            string bar = Timestamp > 0 ? $" @ {TimestampDisplay}" : "";
            return $"{src}{conf}{bar}";
        }
    }
}
