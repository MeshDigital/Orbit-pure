using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using SLSKDONET.Data.Entities;
using SLSKDONET.Models;

namespace SLSKDONET.Engine.Analysis.CueDetr;

/// <summary>Where a track's auto cues come from.</summary>
public enum CueSourceMode
{
    /// <summary>ORBIT's own structure analysis only (the default).</summary>
    Orbit,
    /// <summary>ORBIT's cues, marked "✓AI" where CUE-DETR agrees, plus CUE-DETR's other points as
    /// cyan "AI" memory cues — both opinions side by side on the waveform.</summary>
    Compare,
    /// <summary>Only CUE-DETR's points (snapped to the bar grid), to judge the model on its own.</summary>
    AiOnly,
}

/// <summary>
/// Combines ORBIT's generated cues with CUE-DETR's points. On 68 tracks of hand-placed DJ cues,
/// ORBIT cues that CUE-DETR also found (within one bar) matched a DJ cue 52 % of the time, the rest
/// 23 % — agreement is a strong confidence signal, which Compare mode makes visible.
/// </summary>
public static class CueDetrFusion
{
    public const string AgreeSuffix = " ✓AI";
    public const string AiColour = "#00E5FF";
    private const double AgreeBars = 1.0;

    public static List<CuePointEntity> Apply(
        IReadOnlyList<CuePointEntity> orbitCues, IReadOnlyList<CueDetrPoint> ai,
        string trackHash, double bpm, double downbeat, double duration, CueSourceMode mode)
    {
        double bar = bpm > 0 ? 240.0 / bpm : 0;
        double Snap(double t) => bar <= 0 ? t : Math.Clamp(downbeat + Math.Round((t - downbeat) / bar) * bar, 0, Math.Max(0, duration));

        if (mode == CueSourceMode.Orbit) return orbitCues.ToList();

        var aiCues = new List<CuePointEntity>();
        if (mode == CueSourceMode.AiOnly)
        {
            int n = 0;
            foreach (var p in ai.OrderBy(p => p.Seconds))
            {
                double t = Snap(p.Seconds);
                if (aiCues.Any(c => Math.Abs(c.TimestampInSeconds - t) < 0.01)) continue;
                aiCues.Add(AiCue(trackHash, t, p.Score, $"AI {++n}"));
            }
            return aiCues;
        }

        // Compare
        double tolerance = bar > 0 ? AgreeBars * bar : 2.0;
        var result = new List<CuePointEntity>();
        foreach (var cue in orbitCues)
        {
            bool agreed = !cue.IsLoop && ai.Any(p => Math.Abs(p.Seconds - cue.TimestampInSeconds) <= tolerance);
            if (agreed)
            {
                cue.Label = (cue.Label ?? "") + AgreeSuffix;
                cue.Confidence = Math.Max(cue.Confidence, 0.9f);
            }
            result.Add(cue);
        }
        foreach (var p in ai.OrderBy(p => p.Seconds))
        {
            if (orbitCues.Any(c => Math.Abs(p.Seconds - c.TimestampInSeconds) <= tolerance)) continue;
            double t = Snap(p.Seconds);
            if (result.Any(c => Math.Abs(c.TimestampInSeconds - t) < 0.01)) continue;
            // Invariant: labels also end up in Rekordbox/Serato exports.
            result.Add(AiCue(trackHash, t, p.Score, FormattableString.Invariant($"AI {p.Score:0.00}")));
        }
        return result.OrderBy(c => c.TimestampInSeconds).ToList();
    }

    private static CuePointEntity AiCue(string hash, double t, double score, string label) => new()
    {
        TrackUniqueHash = hash,
        TimestampInSeconds = t,
        Type = CuePointType.PhraseBoundary,
        Label = label,
        Color = AiColour,
        IsAutoGenerated = true,
        Confidence = (float)Math.Clamp(score, 0, 1),
        SlotIndex = -1,
    };

    private sealed record CachedPointDto(double t, double s);
    private sealed record CachedPayloadDto(string? model, List<CachedPointDto>? points);

    /// <summary>Parses cached <see cref="AudioFeaturesEntity.CueDetrJson"/> points without requiring the ONNX runtime.</summary>
    public static List<CueDetrPoint>? ParseCachedPoints(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return null;
        try
        {
            var payload = JsonSerializer.Deserialize<CachedPayloadDto>(json);
            if (payload?.points == null) return null;
            return payload.points.Select(p => new CueDetrPoint(
                (int)Math.Round(p.t * CueDetrFrontEnd.SampleRate / CueDetrFrontEnd.Hop), p.t, p.s)).ToList();
        }
        catch (JsonException)
        {
            return null;
        }
    }

    /// <summary>
    /// CF1 (#603): Returns true when <paramref name="aiPoints"/> contains any point within ±1 beat
    /// of <paramref name="cueTimestampSeconds"/> at <paramref name="bpm"/> (falls back to ±0.5 s when BPM &lt;= 0).
    /// </summary>
    public static bool HasAgreementWithinOneBeat(
        double cueTimestampSeconds,
        IReadOnlyList<CueDetrPoint>? aiPoints,
        double bpm)
    {
        if (aiPoints == null || aiPoints.Count == 0) return false;
        double toleranceSeconds = bpm > 0 ? 60.0 / bpm : 0.5;
        for (int i = 0; i < aiPoints.Count; i++)
        {
            if (Math.Abs(aiPoints[i].Seconds - cueTimestampSeconds) <= toleranceSeconds + 1e-9)
                return true;
        }
        return false;
    }

    /// <summary>
    /// CF1 (#603): Annotates each cue's <see cref="OrbitCue.AiAgreed"/> flag against CUE-DETR points
    /// at ±1 beat tolerance. Hand-placed and imported cues (<see cref="OrbitCue.IsAuto"/> == false)
    /// are NEVER flagged (<see cref="OrbitCue.AiAgreed"/> stays null).
    /// </summary>
    public static void ApplyAgreement(
        IEnumerable<OrbitCue> cues,
        IReadOnlyList<CueDetrPoint>? aiPoints,
        double bpm)
    {
        bool hasAi = aiPoints is { Count: > 0 };
        foreach (var cue in cues)
        {
            if (!cue.IsAuto)
            {
                cue.AiAgreed = null;
                continue;
            }
            cue.AiAgreed = hasAi ? HasAgreementWithinOneBeat(cue.Timestamp, aiPoints, bpm) : null;
        }
    }

    /// <summary>
    /// CF1 (#603): True when a track has auto-generated drop cue(s), no user-placed drop cue, and
    /// none of its auto drops is confirmed by CUE-DETR within ±1 beat. Used to sort unconfirmed
    /// drops to the top of the playlist readiness list.
    /// </summary>
    public static bool HasUnconfirmedAutoDrop(
        AudioFeaturesEntity? features,
        IReadOnlyCollection<CuePointEntity>? cues)
    {
        if (cues == null || cues.Count == 0) return false;

        bool hasAutoDrop = false;
        foreach (var c in cues)
        {
            if (c.Type != CuePointType.Drop) continue;
            if (!c.IsAutoGenerated) return false; // user-confirmed drop
            hasAutoDrop = true;
        }

        if (!hasAutoDrop) return false;

        var aiPoints = ParseCachedPoints(features?.CueDetrJson);
        if (aiPoints == null || aiPoints.Count == 0) return true;

        double bpm = features?.Bpm ?? 0;
        foreach (var c in cues)
        {
            if (c.Type == CuePointType.Drop && c.IsAutoGenerated && HasAgreementWithinOneBeat(c.TimestampInSeconds, aiPoints, bpm))
                return false;
        }

        return true;
    }
}
