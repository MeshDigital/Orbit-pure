using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.Extensions.Logging.Abstractions;
using Moq;
using SLSKDONET.Data.Entities;
using SLSKDONET.Models;
using SLSKDONET.Services;
using SLSKDONET.ViewModels;
using Xunit;

namespace SLSKDONET.Tests.ViewModels;

/// <summary>
/// Library Track Inspector: real cue rows, stale-load dropping, mood bars, multi-selection
/// summary, and rating-save failure feedback.
/// </summary>
public class LibraryTrackInspectorTests
{
    private static PlaylistTrackViewModel Track(string hash, IEventBus? bus = null, ILibraryService? lib = null, Action<PlaylistTrack>? configure = null)
    {
        var model = new PlaylistTrack { TrackUniqueHash = hash, Title = "T " + hash, Artist = "A" };
        configure?.Invoke(model);
        return new PlaylistTrackViewModel(model, eventBus: bus, libraryService: lib);
    }

    private static CuePointEntity Cue(string hash, double t, string name, bool auto = false) => new()
    {
        TrackUniqueHash = hash,
        TimestampInSeconds = t,
        Label = name,
        IsAutoGenerated = auto,
        Color = "#FF0000",
    };

    [Fact]
    public async Task Attach_LoadsCuesFromCuePointsTable_InTimeOrder()
    {
        var cues = new Mock<ICuePointService>();
        cues.Setup(c => c.GetByTrackIdAsync("h1", It.IsAny<CancellationToken>()))
            .ReturnsAsync(new List<CuePointEntity> { Cue("h1", 64, "Drop"), Cue("h1", 8, "Intro", auto: true) });
        var inspector = new LibraryTrackInspectorViewModel(NullLogger.Instance, cues.Object);
        var track = Track("h1");

        await inspector.TryAttachEnhancementsAsync(track);

        Assert.True(track.HasCues);
        Assert.Equal(2, track.CueCount);
        Assert.Equal("Cues (2)", track.CuesTabHeader);
        Assert.Equal(new[] { 8.0, 64.0 }, track.CuesByTime.Select(c => c.Timestamp));
        Assert.False(track.IsLoadingCues);
    }

    [Fact]
    public async Task StaleLoad_IsDropped_WhenSelectionMovesOn()
    {
        var gate = new TaskCompletionSource<List<CuePointEntity>>();
        var cues = new Mock<ICuePointService>();
        cues.Setup(c => c.GetByTrackIdAsync("slow", It.IsAny<CancellationToken>())).Returns(gate.Task);
        var inspector = new LibraryTrackInspectorViewModel(NullLogger.Instance, cues.Object);
        var slow = Track("slow");

        var pending = inspector.TryAttachEnhancementsAsync(slow);
        inspector.ClearEnhancements(); // user clicked elsewhere
        gate.SetResult(new List<CuePointEntity> { Cue("slow", 1, "Late") });
        await pending;

        Assert.False(slow.HasCues);
        Assert.Null(inspector.AttachedTrack);
    }

    [Fact]
    public async Task CueLoadFailure_IsSurfacedOnTheTrack()
    {
        var cues = new Mock<ICuePointService>();
        cues.Setup(c => c.GetByTrackIdAsync("h2", It.IsAny<CancellationToken>())).ThrowsAsync(new InvalidOperationException("db"));
        var inspector = new LibraryTrackInspectorViewModel(NullLogger.Instance, cues.Object);
        var track = Track("h2");

        await inspector.TryAttachEnhancementsAsync(track);

        Assert.True(track.HasCueLoadError);
        Assert.False(track.IsLoadingCues);
    }

    [Fact]
    public void MoodScores_AreRankedAndDropZeroes()
    {
        var scores = PlaylistTrackViewModel.BuildMoodScores(party: 0.2, aggressive: 0, happy: 0.7, relaxed: 0.4, sad: 0);

        Assert.Equal(new[] { "Happy", "Relaxed", "Party" }, scores.Select(s => s.Label));
    }

    [Fact]
    public void MoodBreakdown_ShowsEvenWhenMoodTagIsNeutralAndNoGenreText()
    {
        var track = Track("h3", configure: m => { m.MoodTag = "Neutral"; m.MoodHappy = 0.3; });

        Assert.False(track.HasVibeData);           // the old gate hid the whole block
        Assert.True(track.HasMoodBreakdown);
        Assert.True(track.HasAiClassification);
        Assert.Single(track.MoodScores);
    }

    [Fact]
    public void InspectorTab_IsSharedAcrossTracks()
    {
        var a = Track("ta");
        var b = Track("tb");

        a.SelectedInspectorTab = PlaylistTrackViewModel.InspectorTabFile;
        try
        {
            Assert.Equal(PlaylistTrackViewModel.InspectorTabFile, b.SelectedInspectorTab);
        }
        finally
        {
            a.SelectedInspectorTab = PlaylistTrackViewModel.InspectorTabOverview;
        }
    }

    [Fact]
    public void SearchAgain_PublishesRetryRequest_InsteadOfOnlyFlippingState()
    {
        var bus = new Mock<IEventBus>();
        var track = Track("h4", bus.Object);

        track.SearchAgainCommand.Execute(null);

        bus.Verify(b => b.Publish(It.Is<RetryDownloadFromInspectorEvent>(e => e.TrackGlobalId == "h4")), Times.Once);
    }

    [Fact]
    public void RatingSaveFailure_RaisesErrorToast()
    {
        var bus = new Mock<IEventBus>();
        var lib = new Mock<ILibraryService>();
        lib.Setup(l => l.UpdateRatingAsync("h5", 4)).ThrowsAsync(new InvalidOperationException("locked"));
        var track = Track("h5", bus.Object, lib.Object);

        track.Rating = 4;

        bus.Verify(b => b.Publish(It.Is<ToastRequestedEvent>(e => e.Type == SLSKDONET.Views.NotificationType.Error)), Times.Once);
    }

    [Fact]
    public void MeasureLink_ShowsOnlyForLegacyLoudness_AndRequestsAMeasurement()
    {
        var bus = new EventBusService();
        var requests = new List<MeasureTrackLoudnessRequestedEvent>();
        using var sub = bus.GetEvent<MeasureTrackLoudnessRequestedEvent>().Subscribe(requests.Add);

        var legacy = Track("lg", bus, configure: m => { m.Status = TrackStatus.Downloaded; m.Loudness = 0.8; });
        var measured = Track("ok", bus, configure: m => { m.Status = TrackStatus.Downloaded; m.Loudness = -9.1; });
        var notDownloaded = Track("nd", bus, configure: m => m.Loudness = 0.8);

        Assert.True(legacy.CanMeasureLoudness);
        Assert.False(measured.CanMeasureLoudness);
        Assert.False(notDownloaded.CanMeasureLoudness); // no file to read

        legacy.MeasureLoudnessCommand.Execute(null);
        legacy.MeasureLoudnessCommand.Execute(null); // a second click while measuring is ignored

        Assert.Equal(new[] { "lg" }, requests.Select(r => r.TrackGlobalId));
        Assert.True(legacy.IsMeasuringLoudness);
        Assert.False(legacy.CanMeasureLoudness);
    }

    [Fact]
    public void MultiSelectionSummary_DescribesTheSelection()
    {
        var tracks = new[]
        {
            Track("m1", configure: m => { m.BPM = 124; m.MusicalKey = "8A"; m.CanonicalDuration = 300_000; }),
            Track("m2", configure: m => { m.BPM = 128; m.MusicalKey = "9A"; m.CanonicalDuration = 240_000; }),
            Track("m3", configure: m => { m.CanonicalDuration = 60_000; }),
        };
        var vm = new LibraryMultiSelectionInspectorViewModel(null);

        vm.Update(tracks);

        Assert.Equal("3 tracks selected", vm.Title);
        Assert.Equal("10:00", vm.DurationDisplay);
        Assert.Equal("124–128", vm.BpmRangeDisplay);
        Assert.Equal("2 keys", vm.KeysDisplay);
        Assert.Equal("2 / 3", vm.AnalysedDisplay);
    }
}
