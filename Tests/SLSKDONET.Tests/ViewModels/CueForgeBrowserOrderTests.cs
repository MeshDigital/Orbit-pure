namespace SLSKDONET.Tests.ViewModels;

/// <summary>
/// Cue Forge's docked browser is a snapshot of one playlist. A playlist reordered in the Library
/// (Reorder for better flow, Auto-Arrange, Automix) or by Flow Builder's "Save order" must show
/// that order here too — list, highlighted row, "Track N of M" and Previous/Next.
/// </summary>
public class CueForgeBrowserOrderTests
{
    private sealed class EmptyCueStore : ICuePointService
    {
        public Task CreateManyAsync(IEnumerable<CuePointEntity> cuePoints, CancellationToken cancellationToken = default) =>
            Task.CompletedTask;
        public Task<List<CuePointEntity>> GetByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) =>
            Task.FromResult(new List<CuePointEntity>());
        public Task DeleteAutoGeneratedByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) =>
            Task.CompletedTask;
        public Task DeleteAllByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) =>
            Task.CompletedTask;
    }

    private sealed class StubTransport : ICueForgeTransport
    {
        public bool IsPlaying { get; set; }
        public string? CurrentFilePath { get; set; }
        public string? CurrentTrackHash { get; set; }
        public string Title { get; set; } = "";
        public string Artist { get; set; } = "";
        public double PositionFraction { get; set; }
        public double LengthSeconds { get; set; }
        public IObservable<bool> IsPlayingChanged => Observable.Never<bool>();
        public IObservable<(double Fraction, double LengthSeconds)> PositionChanged => Observable.Never<(double, double)>();
        public IObservable<CueForgeTrackRef?> CurrentTrackChanged => new Subject<CueForgeTrackRef?>();
        public void LoadPaused(string filePath, string title, string artist) { }
        public void Play() => IsPlaying = true;
        public void Pause() => IsPlaying = false;
        public void SeekFraction(double fraction) => PositionFraction = fraction;
        public Task<string?> ResolveFilePathAsync(string trackHash) => Task.FromResult<string?>($"C:/music/{trackHash}.flac");
    }

    private static PlaylistTrack T(string hash) => new()
    {
        TrackUniqueHash = hash,
        Title = hash.ToUpperInvariant(),
        Artist = "Artist",
        Status = TrackStatus.Downloaded,
    };

    private static List<string> BrowserHashes(CueForgeViewModel vm) =>
        vm.BrowserTracks.Select(t => t.GlobalId).ToList();

    [Fact]
    public async Task ReopeningThePage_ReReadsThePlaylistOrder()
    {
        var order = new List<string> { "a", "b", "c" };
        var playlist = new PlaylistJob { Id = Guid.NewGuid(), SourceTitle = "Set", CreatedAt = DateTime.UtcNow };

        var library = new Mock<ILibraryService>();
        library.Setup(l => l.LoadAllPlaylistJobsAsync()).ReturnsAsync(new List<PlaylistJob> { playlist });
        library.Setup(l => l.GetPagedPlaylistTracksAsync(playlist.Id, It.IsAny<int>(), It.IsAny<int>(), It.IsAny<string?>(),
                It.IsAny<bool?>(), It.IsAny<IEnumerable<string>?>(), It.IsAny<string?>(), It.IsAny<TrackSortColumn>(),
                It.IsAny<bool>(), It.IsAny<string?>()))
            .ReturnsAsync(() => order.Select(T).ToList());

        var vm = new CueForgeViewModel(new EmptyCueStore(), new StubTransport(), new AppConfig(),
            libraryService: library.Object, ui: a => { a(); return Task.CompletedTask; });

        Assert.Equal(new[] { "a", "b", "c" }, BrowserHashes(vm));

        // The playlist is reordered while Cue Forge is closed.
        order = new List<string> { "c", "a", "b" };

        await vm.OnViewActivatedAsync();

        Assert.Equal(new[] { "c", "a", "b" }, BrowserHashes(vm));
        library.Verify(l => l.GetPagedPlaylistTracksAsync(playlist.Id, It.IsAny<int>(), It.IsAny<int>(), It.IsAny<string?>(),
            It.IsAny<bool?>(), It.IsAny<IEnumerable<string>?>(), It.IsAny<string?>(), It.IsAny<TrackSortColumn>(),
            It.IsAny<bool>(), It.IsAny<string?>()), Times.Exactly(2));
    }

    [Fact]
    public async Task OrderChangedEvent_ReReadsTheSelectedPlaylist()
    {
        var order = new List<string> { "a", "b", "c" };
        var playlist = new PlaylistJob { Id = Guid.NewGuid(), SourceTitle = "Set", CreatedAt = DateTime.UtcNow };

        var library = new Mock<ILibraryService>();
        library.Setup(l => l.LoadAllPlaylistJobsAsync()).ReturnsAsync(new List<PlaylistJob> { playlist });
        library.Setup(l => l.GetPagedPlaylistTracksAsync(playlist.Id, It.IsAny<int>(), It.IsAny<int>(), It.IsAny<string?>(),
                It.IsAny<bool?>(), It.IsAny<IEnumerable<string>?>(), It.IsAny<string?>(), It.IsAny<TrackSortColumn>(),
                It.IsAny<bool>(), It.IsAny<string?>()))
            .ReturnsAsync(() => order.Select(T).ToList());

        var eventBus = new EventBusService();
        var vm = new CueForgeViewModel(new EmptyCueStore(), new StubTransport(), new AppConfig(),
            libraryService: library.Object, eventBus: eventBus, ui: a => { a(); return Task.CompletedTask; });

        Assert.Equal(new[] { "a", "b", "c" }, BrowserHashes(vm));

        order = new List<string> { "b", "c", "a" };
        eventBus.Publish(new PlaylistTrackOrderChangedEvent(playlist.Id, order.Select(_ => Guid.NewGuid()).ToList()));

        Assert.True(await WaitUntilAsync(() => BrowserHashes(vm).SequenceEqual(new[] { "b", "c", "a" })),
            "the browser should have re-read the playlist's new order");
    }

    [Fact]
    public async Task OrderChangedEvent_ForAnotherPlaylist_LeavesTheBrowserAlone()
    {
        var order = new List<string> { "a", "b", "c" };
        var playlist = new PlaylistJob { Id = Guid.NewGuid(), SourceTitle = "Set", CreatedAt = DateTime.UtcNow };

        var library = new Mock<ILibraryService>();
        library.Setup(l => l.LoadAllPlaylistJobsAsync()).ReturnsAsync(new List<PlaylistJob> { playlist });
        library.Setup(l => l.GetPagedPlaylistTracksAsync(playlist.Id, It.IsAny<int>(), It.IsAny<int>(), It.IsAny<string?>(),
                It.IsAny<bool?>(), It.IsAny<IEnumerable<string>?>(), It.IsAny<string?>(), It.IsAny<TrackSortColumn>(),
                It.IsAny<bool>(), It.IsAny<string?>()))
            .ReturnsAsync(() => order.Select(T).ToList());

        var eventBus = new EventBusService();
        var vm = new CueForgeViewModel(new EmptyCueStore(), new StubTransport(), new AppConfig(),
            libraryService: library.Object, eventBus: eventBus, ui: a => { a(); return Task.CompletedTask; });

        eventBus.Publish(new PlaylistTrackOrderChangedEvent(Guid.NewGuid(), Array.Empty<Guid>()));

        // Give a wrong-but-possible background reload time to happen, then check nothing changed.
        await Task.Delay(150);
        Assert.Equal(new[] { "a", "b", "c" }, BrowserHashes(vm));
        library.Verify(l => l.GetPagedPlaylistTracksAsync(playlist.Id, It.IsAny<int>(), It.IsAny<int>(), It.IsAny<string?>(),
            It.IsAny<bool?>(), It.IsAny<IEnumerable<string>?>(), It.IsAny<string?>(), It.IsAny<TrackSortColumn>(),
            It.IsAny<bool>(), It.IsAny<string?>()), Times.Once);
    }

    private static async Task<bool> WaitUntilAsync(Func<bool> condition, int timeoutMs = 3000)
    {
        var deadline = Environment.TickCount64 + timeoutMs;
        while (Environment.TickCount64 < deadline)
        {
            if (condition()) return true;
            await Task.Delay(20);
        }
        return condition();
    }
}
