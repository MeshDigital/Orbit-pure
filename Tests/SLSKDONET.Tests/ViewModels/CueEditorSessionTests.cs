/// <summary>
/// The shared cue-editing engine behind Cue Forge and the Flow Builder decks, driven directly with
/// an in-memory cue store and a fake audition port (no player, view, DB or config file).
/// Grid: 120 BPM from 0 s (beat 0.5 s, bar 2 s), track 300 s.
/// </summary>
public class CueEditorSessionTests
{
    private const string Hash = "track-x";

    private sealed class FakeCueStore : ICuePointService
    {
        public readonly Dictionary<string, List<CuePointEntity>> Rows = new();
        public bool FailWrites;
        public int Saves;
        public Task CreateManyAsync(IEnumerable<CuePointEntity> cuePoints, CancellationToken cancellationToken = default)
        {
            if (FailWrites) throw new InvalidOperationException("database is locked");
            foreach (var c in cuePoints)
            {
                if (!Rows.TryGetValue(c.TrackUniqueHash, out var list)) Rows[c.TrackUniqueHash] = list = new();
                list.Add(c);
            }
            Saves++;
            return Task.CompletedTask;
        }
        public Task<List<CuePointEntity>> GetByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) =>
            Task.FromResult(Rows.TryGetValue(trackUniqueHash, out var l) ? l.Select(Copy).ToList() : new List<CuePointEntity>());
        public Task DeleteAutoGeneratedByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default)
        {
            if (Rows.TryGetValue(trackUniqueHash, out var l)) l.RemoveAll(c => c.IsAutoGenerated);
            return Task.CompletedTask;
        }
        public Task DeleteAllByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default)
        {
            if (FailWrites) throw new InvalidOperationException("database is locked");
            Rows.Remove(trackUniqueHash);
            return Task.CompletedTask;
        }
        private static CuePointEntity Copy(CuePointEntity e) => new()
        {
            TrackUniqueHash = e.TrackUniqueHash, TimestampInSeconds = e.TimestampInSeconds, Label = e.Label, Type = e.Type,
            Color = e.Color, SlotIndex = e.SlotIndex, IsLoop = e.IsLoop, LoopEndSeconds = e.LoopEndSeconds,
            IsAutoGenerated = e.IsAutoGenerated, Confidence = e.Confidence,
        };
    }

    private sealed class FakeAudition : ICueAudition
    {
        public double PositionSeconds { get; set; }
        public bool IsPlaying { get; set; }
        public readonly List<double> Plays = new();
        public readonly List<OrbitCue> Jumps = new();
        public void PlayFrom(double seconds) { Plays.Add(seconds); IsPlaying = true; }
        public void JumpToCue(OrbitCue cue) => Jumps.Add(cue);
    }

    private static CueTrackInfo Track(string hash = Hash) => new(hash, "Title", "C:/music/x.flac", 120, 0, 300);

    private static (CueEditorSession Session, FakeCueStore Store, FakeAudition Audio) Create(
        FakeCueStore? store = null, CueSessionRegistry? registry = null, bool auditionAfterEdits = false, string name = "Test")
    {
        store ??= new FakeCueStore();
        var audio = new FakeAudition();
        var session = new CueEditorSession(store, audio, registry) { AuditionAfterEdits = auditionAfterEdits, EditorName = name };
        session.Load(Track(), store.Rows.TryGetValue(Hash, out var rows) ? rows.ToList() : new List<CuePointEntity>());
        return (session, store, audio);
    }

    [Fact]
    public void AddAtPlayhead_SnapsToTheGrid_TakesTheFirstFreePad_AndIsDirty()
    {
        var (s, _, audio) = Create();
        audio.PositionSeconds = 10.3;

        s.AddCueAtPlayheadCommand.Execute().Subscribe();
        audio.PositionSeconds = 20.0;
        s.AddCueAtPlayheadCommand.Execute().Subscribe();

        Assert.Equal(new[] { (10.5, 0, "Cue A"), (20.0, 1, "Cue B") }, s.Cues.Select(c => (c.Timestamp, c.SlotIndex, c.Name)));
        Assert.Same(s.Cues[1], s.SelectedCue);
        Assert.Same(s.Cues[1], s.HotCuePads[1].Cue);
        Assert.True(s.IsDirty);
        Assert.False(s.IsSaved);
        Assert.Empty(audio.Plays); // Cue Forge-style host: adding doesn't play
    }

    [Fact]
    public void AuditionAfterEdits_PlaysTheNewCue()
    {
        var (s, _, audio) = Create(auditionAfterEdits: true);

        s.AddCueAtCommand.Execute(41.2).Subscribe();

        Assert.Equal(new[] { 41.0 }, audio.Plays);
    }

    [Fact]
    public void Drag_WithDragStart_KeepsTheLiveSnappedPosition_AndIsOneUndoStep()
    {
        // Cue Forge: its waveform snaps while dragging (Shift = free), so release must not re-snap.
        var (s, _, _) = Create();
        s.AddCueAtCommand.Execute(10.0).Subscribe();
        var cue = s.Cues.Single();
        (double, double)? moved = null;
        s.CueMoved += (_, m) => moved = m;

        s.CueDragStartedCommand.Execute(cue).Subscribe();
        cue.Timestamp = 23.37; // Shift-drag: placed freely
        s.CueUpdatedCommand.Execute(cue).Subscribe();

        Assert.Equal(23.37, cue.Timestamp, 6);
        Assert.Equal((10.0, 23.37), moved);
        s.UndoCommand.Execute().Subscribe();
        Assert.Equal(10.0, s.Cues.Single().Timestamp, 6);
        s.UndoCommand.Execute().Subscribe();
        Assert.Empty(s.Cues);
    }

    [Fact]
    public void Drag_WithoutDragStart_SnapsOnRelease_WhenTheHostAsks()
    {
        var store = new FakeCueStore();
        var session = new CueEditorSession(store, new FakeAudition()) { SnapOnDragRelease = true };
        session.Load(Track(), Array.Empty<CuePointEntity>());
        session.SnapResolution = "Bar";
        session.AddCueAtCommand.Execute(10.0).Subscribe();
        var cue = session.Cues.Single();

        cue.Timestamp = 14.7;
        session.CueUpdatedCommand.Execute(cue).Subscribe();

        Assert.Equal(14.0, cue.Timestamp, 6);
        session.UndoCommand.Execute().Subscribe();
        Assert.Equal(10.0, session.Cues.Single().Timestamp, 6);
    }

    [Fact]
    public void Rename_CommitsTrimmed_RevertsOnEscape_EmptyIsIgnored_AndIsUndoable()
    {
        var (s, _, _) = Create();
        s.AddCueAtCommand.Execute(4.0).Subscribe();
        var cue = s.Cues.Single();

        s.EditingCueName = "Scratch";
        s.RevertCueName();
        Assert.Equal(("Cue A", "Cue A"), (cue.Name, s.EditingCueName));

        s.EditingCueName = "   ";
        s.CommitCueName();
        Assert.Equal("Cue A", cue.Name);

        s.EditingCueName = "  Vocal in ";
        s.CommitCueName();
        Assert.Equal("Vocal in", cue.Name);
        Assert.Equal("Vocal in", s.HotCuePads[0].CueName);

        s.UndoCommand.Execute().Subscribe();
        Assert.Equal("Cue A", s.Cues.Single().Name);
    }

    [Fact]
    public void Delete_ThenUndo_RestoresTheCue_AndRedoDeletesAgain()
    {
        var (s, _, _) = Create();
        s.AddCueAtCommand.Execute(8.0).Subscribe();

        s.DeleteSelectedCueCommand.Execute().Subscribe();
        Assert.Empty(s.Cues);
        Assert.Null(s.SelectedCue);
        Assert.Null(s.HotCuePads[0].Cue);

        s.UndoCommand.Execute().Subscribe();
        Assert.Equal(8.0, Assert.Single(s.Cues).Timestamp, 6);
        Assert.NotNull(s.HotCuePads[0].Cue);

        s.RedoCommand.Execute().Subscribe();
