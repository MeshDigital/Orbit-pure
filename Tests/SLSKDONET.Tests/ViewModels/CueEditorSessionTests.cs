    }

    [Fact]
    public void AssigningATakenPad_MovesThePreviousHolderToMemory()
    {
        var (s, _, _) = Create();
        s.AddCueAtCommand.Execute(10.0).Subscribe();
        var first = s.SelectedCue!;
        s.AddCueAtCommand.Execute(20.0).Subscribe();
