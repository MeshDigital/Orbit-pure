    [Fact]
    public void Commands_AreDisabled_WithoutATrack_OrWhileLocked()
    {
        var session = new CueEditorSession(new FakeCueStore(), new FakeAudition());
        Assert.False(((System.Windows.Input.ICommand)session.AddCueAtPlayheadCommand).CanExecute(null));

        session.Load(Track(), Array.Empty<CuePointEntity>());
        Assert.True(((System.Windows.Input.ICommand)session.AddCueAtPlayheadCommand).CanExecute(null));

        session.IsLocked = true;
        Assert.False(((System.Windows.Input.ICommand)session.AddCueAtPlayheadCommand).CanExecute(null));
    }
