    }

    [Fact]
    public void Loops_InOut_QuickLoop_HalfDouble_AndClear()
    {
        var (s, _, audio) = Create();
        int removed = 0;
        s.ActiveLoopRemoved += (_, _) => removed++;

        audio.PositionSeconds = 8.1; s.SetLoopInCommand.Execute().Subscribe();
        audio.PositionSeconds = 15.9; s.SetLoopOutCommand.Execute().Subscribe();
        var loop = Assert.Single(s.Cues);
        Assert.Equal((true, 8.0, 16.0, "4 bars", -1), (loop.IsLoop, loop.Timestamp, loop.LoopEndSeconds, loop.Name, loop.SlotIndex));

        s.LoopHalfCommand.Execute().Subscribe();
        Assert.Equal((12.0, "2 bars"), (loop.LoopEndSeconds, loop.Name));
        s.SetQuickLoopCommand.Execute("8").Subscribe(); // a selected loop is resized
        Assert.Equal(24.0, loop.LoopEndSeconds, 6);

        s.SelectedCue = null;
        audio.PositionSeconds = 40.2;
        s.SetQuickLoopCommand.Execute(1).Subscribe();     // nothing selected: new loop at the playhead
        Assert.Equal(2, s.Cues.Count(c => c.IsLoop));
        Assert.Equal((40.0, 42.0), (s.SelectedCue!.Timestamp, s.SelectedCue.LoopEndSeconds));

        s.ClearLoopCommand.Execute().Subscribe();
        Assert.Single(s.Cues, c => c.IsLoop);
        Assert.Equal(1, removed);
    }

    [Fact]
    public void Pads_EmptySetsACueInThatSlot_AssignedJumps_ClearKeepsAMemoryCue()
    {
        var (s, _, audio) = Create();
        audio.PositionSeconds = 30.2;

        s.TriggerPadCommand.Execute(s.HotCuePads[5]).Subscribe();
        var cue = Assert.Single(s.Cues);
