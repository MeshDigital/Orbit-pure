    }

    [Fact]
    public async Task Save_WritesTheRows_ClearsDirty_AndReloadsTheSame()
    {
        var (s, store, _) = Create();
        int saved = 0;
        s.Saved += (_, _) => saved++;
        s.AddCueAtCommand.Execute(4.0).Subscribe();
        s.SetSelectedCueColorCommand.Execute("#305AFF").Subscribe();
        s.SetQuickLoopCommand.Execute(4).Subscribe();

        Assert.True(await s.SaveAsync());

        Assert.False(s.IsDirty);
        Assert.True(s.IsSaved);
        Assert.Equal(1, saved);
        Assert.StartsWith("Saved 1 hot cue, 1 loop", s.StatusText);
        var rows = store.Rows[Hash];
        var hot = rows.Single(r => !r.IsLoop);
        Assert.Equal((0, "#305AFF", false), (hot.SlotIndex, hot.Color, hot.IsAutoGenerated));
        var loop = rows.Single(r => r.IsLoop);
        Assert.Equal((-1, 4.0, 12.0), (loop.SlotIndex, loop.TimestampInSeconds, loop.LoopEndSeconds));

        var (reloaded, _, _) = Create(store);
        Assert.Equal(2, reloaded.Cues.Count);
        Assert.False(reloaded.IsDirty);
        Assert.False(reloaded.CanUndo);
    }

    [Fact]
    public async Task SaveFailure_KeepsTheEdits_AndTheDirtyFlag_AndReportsAnError()
    {
        var (s, store, _) = Create();
        int saved = 0;
        s.Saved += (_, _) => saved++;
        s.AddCueAtCommand.Execute(4.0).Subscribe();
        store.FailWrites = true;

        Assert.False(await s.SaveAsync());

        Assert.True(s.IsDirty);
        Assert.False(s.IsSaved);
        Assert.True(s.IsStatusError);
        Assert.Contains("NOT written", s.StatusText);
        Assert.Single(s.Cues);
        Assert.Equal(0, saved);

        store.FailWrites = false;
        Assert.True(await s.SaveIfDirtyAsync()); // the retry works
        Assert.False(s.IsStatusError);
    }

    [Fact]
    public async Task Revert_LoadsTheSavedCues_IsUndoable_AndCanBeCancelled()
    {
        var (s, _, _) = Create();
        s.AddCueAtCommand.Execute(4.0).Subscribe();
        await s.SaveAsync();
        s.AddCueAtCommand.Execute(9.0).Subscribe();

        s.ConfirmRevert = () => Task.FromResult(false);
        await s.RevertAsync();
        Assert.Equal(2, s.Cues.Count);

        s.ConfirmRevert = () => Task.FromResult(true);
        await s.RevertAsync();
        Assert.Single(s.Cues);
        Assert.False(s.IsDirty);

        s.UndoCommand.Execute().Subscribe();
        Assert.Equal(2, s.Cues.Count);
        Assert.True(s.IsDirty);
    }

    [Fact]
    public async Task TwoEditors_OnOneTrack_CleanOneFollowsTheSave_DirtyOneIsWarned()
    {
        var store = new FakeCueStore();
        var registry = new CueSessionRegistry(new AppConfig());
        var (forge, _, _) = Create(store, registry, name: "Cue Forge");
        var (deck, _, _) = Create(store, registry, name: "Flow Builder");

        // Clean peer: reloads straight away.
        deck.AddCueAtCommand.Execute(10.0).Subscribe();
        await deck.SaveAsync();
        Assert.Equal(10.0, Assert.Single(forge.Cues).Timestamp, 6);
        Assert.False(forge.IsDirty);
        Assert.Contains("Flow Builder", forge.StatusText);

        // Dirty peer: keeps its edits and is told.
        forge.AddCueAtCommand.Execute(50.0).Subscribe();
        deck.AddCueAtCommand.Execute(20.0).Subscribe();
        await deck.SaveAsync();
        Assert.Equal(2, forge.Cues.Count);
        Assert.Contains(forge.Cues, c => Math.Abs(c.Timestamp - 50.0) < 1e-6);
        Assert.True(forge.HasExternalChanges);
        Assert.True(forge.IsStatusError);

        // Revert takes the other editor's version.
        await forge.RevertAsync();
        Assert.Equal(new[] { 10.0, 20.0 }, forge.Cues.Select(c => c.Timestamp));
        Assert.False(forge.HasExternalChanges);
    }

