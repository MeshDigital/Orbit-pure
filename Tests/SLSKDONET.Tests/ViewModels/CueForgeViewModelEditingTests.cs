        Assert.Equal(offset + 10 * beat, CueForgeGrid.Snap(t, bpm, offset, 1), 9);
        Assert.Equal(offset + 12 * beat, CueForgeGrid.Snap(offset + 11 * beat, bpm, offset, 4), 9);
