    [Fact]
    public void BarBeat_CountsFromTheDownbeat()
    {
        Assert.Equal((1, 1), CueForgeGrid.BarBeat(0.5, 120, 0.5));
        Assert.Equal((2, 3), CueForgeGrid.BarBeat(0.5 + 2.0 + 1.0, 120, 0.5));
    }

    [Fact]
    public void ZoomAround_KeepsTheAnchorFixed()
    {
        double scroll = 0.2, oldZoom = 2, newZoom = 8, anchor = 0.25;
        double before = scroll + anchor / oldZoom;
        double next = CueForgeGrid.ZoomAround(scroll, oldZoom, newZoom, anchor);
        Assert.Equal(before, next + anchor / newZoom, 9);
    }

    [Fact]
    public void Scroll_CanReachTheEndOfTheTrack()
    {
        // Regression: scroll used to be in window units, so at 4x the last half of the track was unreachable.
        Assert.Equal(0.75, CueForgeGrid.MaxScroll(4), 9);
        Assert.Equal(0.75, CueForgeGrid.ClampScroll(5, 4), 9);
    }

    [Fact]
    public void FollowScroll_PagesOnlyWhenThePlayheadLeavesTheView()
    {
        Assert.Equal(0.1, CueForgeGrid.FollowScroll(0.15, 0.1, 4), 9);
