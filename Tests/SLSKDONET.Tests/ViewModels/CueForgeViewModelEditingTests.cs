/// <summary>
/// Cue Forge editing, persistence and shared-player behaviour, driven through the view model's
/// test constructor with an in-memory cue store and a fake transport (no real player, DB or config).
/// Without analysis data the grid is 120 BPM from 0 s (beat = 0.5 s, bar = 2 s) and the track 300 s.
/// </summary>
public class CueForgeViewModelEditingTests
{
    private const string Hash = "track-a";

    private sealed class FakeCueStore : ICuePointService
    {
        public readonly Dictionary<string, List<CuePointEntity>> Rows = new();
        public int Saves;
        public Task CreateManyAsync(IEnumerable<CuePointEntity> cuePoints, CancellationToken cancellationToken = default)
        {
            foreach (var c in cuePoints)
            {
                if (!Rows.TryGetValue(c.TrackUniqueHash, out var list)) Rows[c.TrackUniqueHash] = list = new();
                list.Add(c);
            }
            Saves++;
            return Task.CompletedTask;
        }
        public Task<List<CuePointEntity>> GetByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) =>
            Task.FromResult(Rows.TryGetValue(trackUniqueHash, out var l) ? l.ToList() : new List<CuePointEntity>());
        public Task DeleteAutoGeneratedByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default)
        {
            if (Rows.TryGetValue(trackUniqueHash, out var l)) l.RemoveAll(c => c.IsAutoGenerated);
            return Task.CompletedTask;
        }
        public Task DeleteAllByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default)
        {
            Rows.Remove(trackUniqueHash);
            return Task.CompletedTask;
        }
    }

    private sealed class FakeTransport : ICueForgeTransport
    {
        public bool IsPlaying { get; set; }
        public string? CurrentFilePath { get; set; }
        public string? CurrentTrackHash { get; set; }
        public string Title { get; set; } = "";
        public string Artist { get; set; } = "";
        public double PositionFraction { get; set; }
        public double LengthSeconds { get; set; }
        public readonly List<string> Loads = new();
        public readonly List<double> Seeks = new();
        public readonly Subject<CueForgeTrackRef?> TrackChanges = new();

        public IObservable<bool> IsPlayingChanged => Observable.Never<bool>();
        public IObservable<(double Fraction, double LengthSeconds)> PositionChanged => Observable.Never<(double, double)>();
        public IObservable<CueForgeTrackRef?> CurrentTrackChanged => TrackChanges;

        public void LoadPaused(string filePath, string title, string artist)
        {
            Loads.Add(filePath);
            CurrentFilePath = filePath; Title = title; Artist = artist;
            IsPlaying = false;
            LengthSeconds = filePath.Contains("track-") ? 300 : 200;
        }
        public void Play() => IsPlaying = true;
        public void Pause() => IsPlaying = false;
        public void SeekFraction(double fraction) { Seeks.Add(fraction); PositionFraction = fraction; }
        public Task<string?> ResolveFilePathAsync(string trackHash) => Task.FromResult<string?>($"C:/music/{trackHash}.flac");
    }

    private static (CueForgeViewModel Vm, FakeCueStore Store, FakeTransport Player) Create()
    {
        var store = new FakeCueStore();
        var player = new FakeTransport { CurrentFilePath = "C:/music/other.mp3", Title = "Other", Artist = "Someone", PositionFraction = 0.4, LengthSeconds = 200 };
        var vm = new CueForgeViewModel(store, player, new AppConfig(), ui: a => { a(); return Task.CompletedTask; });
        return (vm, store, player);
    }

    private static async Task<(CueForgeViewModel Vm, FakeCueStore Store, FakeTransport Player)> CreateLoaded()
    {
        var t = Create();
        await t.Vm.LoadTrackAsync(Hash, "Title", "Artist");
        return t;
    }

    [Fact]
    public async Task OpeningATrack_DoesNotTakeOverTheSharedPlayer()
    {
        var (vm, _, player) = await CreateLoaded();

        Assert.Empty(player.Loads);
        Assert.False(vm.IsAttachedToPlayer);

        // Clicking the waveform only moves the playhead; it never interrupts other playback.
        await vm.SeekPlayheadCommand.Execute(12.0);
        Assert.Empty(player.Loads);
        Assert.Empty(player.Seeks);
        Assert.Equal(12.0, vm.CurrentPlayPosition);
    }

    [Fact]
    public async Task Play_BorrowsPlayer_AndLeavingHandsItBack()
    {
        var (vm, _, player) = await CreateLoaded();
        await vm.SeekPlayheadCommand.Execute(30.0);

        await vm.PlayPauseCommand.Execute();
        Assert.Equal(new[] { "C:/music/track-a.flac" }, player.Loads);
        Assert.True(player.IsPlaying);
        Assert.Equal(30.0 / 300.0, player.Seeks.Last(), 6);

        vm.OnViewDeactivated();
        Assert.False(player.IsPlaying);
        Assert.Equal("C:/music/other.mp3", player.CurrentFilePath);
        Assert.Equal(0.4, player.Seeks.Last(), 6);
    }

    [Fact]
    public async Task Leaving_AfterThePlayerMovedOn_DoesNotOverrideIt()
    {
        var (vm, _, player) = await CreateLoaded();
        await vm.PlayPauseCommand.Execute();
        player.LoadPaused("C:/music/user-choice.mp3", "Chosen", "");
        player.TrackChanges.OnNext(null);

        vm.OnViewDeactivated();
        Assert.Equal("C:/music/user-choice.mp3", player.CurrentFilePath);
    }

    [Fact]
    public async Task AddCueAtPlayhead_SnapsToBeat_AndTakesFirstFreePad()
    {
        var (vm, _, _) = await CreateLoaded();
        await vm.SeekPlayheadCommand.Execute(1.3);

        await vm.AddCueAtPlayheadCommand.Execute();

        var cue = Assert.Single(vm.WorkingCues);
        Assert.Equal(1.5, cue.Timestamp, 6);
        Assert.Equal(0, cue.SlotIndex);
        Assert.Same(cue, vm.SelectedCue);
        Assert.Same(cue, vm.HotCuePads[0].Cue);
        Assert.True(vm.HasUncommittedChanges);

        vm.SnapToGrid = false;
        await vm.SeekPlayheadCommand.Execute(7.3);
        await vm.AddCueAtPlayheadCommand.Execute();
        Assert.Contains(vm.WorkingCues, c => Math.Abs(c.Timestamp - 7.3) < 1e-9 && c.SlotIndex == 1);
    }

    [Fact]
    public async Task EmptyPad_SetsCueInThatSlot_AssignedPad_JumpsAndPlays()
    {
        var (vm, _, player) = await CreateLoaded();
        await vm.SeekPlayheadCommand.Execute(10.1);

        await vm.TriggerPadCommand.Execute(vm.HotCuePads[5]);
        var cue = Assert.Single(vm.WorkingCues);
        Assert.Equal(5, cue.SlotIndex);
        Assert.Equal(10.0, cue.Timestamp, 6);
        Assert.Empty(player.Loads);

        await vm.SeekPlayheadCommand.Execute(100.0);
        await vm.TriggerPadCommand.Execute(vm.HotCuePads[5]);
        Assert.True(player.IsPlaying);
        Assert.Equal(10.0 / 300.0, player.Seeks.Last(), 6);
    }

    [Fact]
    public async Task ClearPad_KeepsCueAsMemoryCue()
    {
        var (vm, _, _) = await CreateLoaded();
        await vm.TriggerPadCommand.Execute(vm.HotCuePads[2]);
        var cue = vm.WorkingCues.Single();

        await vm.ClearPadCommand.Execute(vm.HotCuePads[2]);

        Assert.Equal(-1, cue.SlotIndex);
        Assert.Null(vm.HotCuePads[2].Cue);
        Assert.Equal("Memory", cue.KindDisplay);
    }

    [Fact]
    public async Task Rename_CommitsOnEnter_RevertsOnEscape_AndIsUndoable()
    {
        var (vm, _, _) = await CreateLoaded();
        await vm.AddCueAtPlayheadCommand.Execute();
        var cue = vm.WorkingCues.Single();
        string original = cue.Name;

        vm.EditingCueName = "Scratch";
        vm.RevertCueName();
        Assert.Equal(original, cue.Name);
        Assert.Equal(original, vm.EditingCueName);

        vm.EditingCueName = "  Vocal in  ";
        vm.CommitCueName();
        Assert.Equal("Vocal in", cue.Name);
        Assert.Equal("Vocal in", vm.HotCuePads[0].CueName);

        await vm.UndoCommand.Execute();
        Assert.Equal(original, vm.WorkingCues.Single().Name);
    }

    [Fact]
    public async Task Delete_IsUndoable()
    {
        var (vm, _, _) = await CreateLoaded();
        await vm.SeekPlayheadCommand.Execute(20.0);
        await vm.AddCueAtPlayheadCommand.Execute();

        await vm.DeleteSelectedCueCommand.Execute();
        Assert.Empty(vm.WorkingCues);
        Assert.Null(vm.SelectedCue);

        await vm.UndoCommand.Execute();
        Assert.Equal(20.0, Assert.Single(vm.WorkingCues).Timestamp, 6);
    }

    [Fact]
    public async Task Save_PersistsThroughCueService_AndSurvivesReload()
    {
        var (vm, store, _) = await CreateLoaded();
        await vm.SeekPlayheadCommand.Execute(4.0);
        await vm.TriggerPadCommand.Execute(vm.HotCuePads[3]);
        await vm.SetSelectedCueColorCommand.Execute("#305AFF");
        await vm.SetQuickLoopCommand.Execute("4");

        await vm.CommitChangesCommand.Execute();
        Assert.False(vm.HasUncommittedChanges);
        Assert.True(vm.IsSaved);

        var rows = store.Rows[Hash];
        Assert.Equal(2, rows.Count);
        var hot = rows.Single(r => !r.IsLoop);
        Assert.Equal(3, hot.SlotIndex);
        Assert.Equal("#305AFF", hot.Color);
        Assert.False(hot.IsAutoGenerated);
        var loop = rows.Single(r => r.IsLoop);
        Assert.Equal(-1, loop.SlotIndex);              // a loop never steals pad A
        Assert.Equal(4.0, loop.TimestampInSeconds, 6); // started at the selected cue
        Assert.Equal(12.0, loop.LoopEndSeconds, 6);    // 4 bars at 120 BPM

        var (fresh, _, _) = Create();
        var reloaded = new CueForgeViewModel(store, new FakeTransport(), new AppConfig(), ui: a => { a(); return Task.CompletedTask; });
        await reloaded.LoadTrackAsync(Hash, "Title", "Artist");
        Assert.Equal(2, reloaded.WorkingCues.Count);
        Assert.Equal(3, reloaded.HotCuePads[3].Cue?.SlotIndex);
        Assert.False(reloaded.HasUncommittedChanges);
        fresh.Dispose();
        reloaded.Dispose();
    }

    [Fact]
    public async Task SwitchingTracks_AutoSavesTheDirtyDraft()
    {
        var (vm, store, _) = await CreateLoaded();
        await vm.AddCueAtPlayheadCommand.Execute();

        await vm.LoadTrackAsync("track-b", "Other", "Artist");

        Assert.Single(store.Rows[Hash]);
        Assert.Equal("track-b", vm.TrackHash);
        Assert.Empty(vm.WorkingCues);
    }

    [Fact]
    public async Task SetSelectedCueSlot_AcceptsBoxedIntFromICommand_AndMovesPriorHolder()
    {
        var (vm, _, _) = await CreateLoaded();
        await vm.TriggerPadCommand.Execute(vm.HotCuePads[0]);
        var first = vm.WorkingCues.Single();
        await vm.SeekPlayheadCommand.Execute(50.0);
        await vm.TriggerPadCommand.Execute(vm.HotCuePads[1]);
        var second = vm.WorkingCues.Single(c => c != first);
        vm.SelectedCue = second;

        ICommand command = vm.SetSelectedCueSlotCommand;
        command.Execute((object)0);

        Assert.Equal(0, second.SlotIndex);
        Assert.Equal(-1, first.SlotIndex);
        Assert.Same(second, vm.HotCuePads[0].Cue);
    }

    [Fact]
    public async Task LoopInOut_CreatesSnappedLoop_AndHalveDoubleResizeIt()
    {
        var (vm, _, _) = await CreateLoaded();
        await vm.SeekPlayheadCommand.Execute(8.1);
        await vm.SetLoopInCommand.Execute();
        await vm.SeekPlayheadCommand.Execute(15.9);
        await vm.SetLoopOutCommand.Execute();

        var loop = Assert.Single(vm.WorkingCues);
        Assert.True(loop.IsLoop);
        Assert.Equal(8.0, loop.Timestamp, 6);
        Assert.Equal(16.0, loop.LoopEndSeconds, 6);
        Assert.Equal("4 bars", loop.Name);

        await vm.LoopHalfCommand.Execute();
        Assert.Equal(12.0, loop.LoopEndSeconds, 6);
        await vm.LoopDoubleCommand.Execute();
        Assert.Equal(16.0, loop.LoopEndSeconds, 6);
    }

    [Fact]
    public async Task NudgeBeat_MovesSelectedCue_AndReplaysFromIt()
    {
        var (vm, _, player) = await CreateLoaded();
        await vm.SeekPlayheadCommand.Execute(10.0);
        await vm.AddCueAtPlayheadCommand.Execute();

        await vm.NudgeCueCommand.Execute("+beat");

        Assert.Equal(10.5, vm.SelectedCue!.Timestamp, 6);
        Assert.True(player.IsPlaying);
        Assert.Equal(10.5 / 300.0, player.Seeks.Last(), 6);
    }

    [Fact]
    public void CueForgePage_HasNoStringLiteralParameterForIntCommands()
    {
        var xaml = File.ReadAllText(FindRepoFile(Path.Combine("Views", "Avalonia", "CueForgePage.axaml")));
        // ReactiveCommand<int> rejects the string a XAML literal produces (see XamlCommandParameterTypeTests).
        foreach (var intCommand in new[] { "SetSelectedCueSlotCommand", "SetNumberedDropAtPlayheadCommand" })
            Assert.DoesNotMatch(new Regex(intCommand + @"[^>]*CommandParameter=""-?\d+"""), xaml);
        Assert.DoesNotMatch(new Regex(@"CommandParameter=""-?\d+""[^>]*(SetSelectedCueSlotCommand|SetNumberedDropAtPlayheadCommand)"), xaml);
    }

    private static string FindRepoFile(string relative)
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, relative)))
            dir = dir.Parent;
        Assert.NotNull(dir);
        return Path.Combine(dir!.FullName, relative);
    }
