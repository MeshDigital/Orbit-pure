/// <summary>
/// Intro end / Outro section markers in the shared cue session (both editors), their suggestion
/// from phrase data, and click-to-prelisten on cue flags (click = play from the cue, drag = move).
/// Grid: 120 BPM from 0 s (beat 0.5 s, bar 2 s), track 300 s.
/// </summary>
public class SectionMarkerAndPrelistenTests
{
    private const string Hash = "track-s";

    private sealed class Store : ICuePointService
    {
        public readonly List<CuePointEntity> Rows = new();
        public Task CreateManyAsync(IEnumerable<CuePointEntity> cuePoints, CancellationToken ct = default) { Rows.AddRange(cuePoints); return Task.CompletedTask; }
        public Task<List<CuePointEntity>> GetByTrackIdAsync(string hash, CancellationToken ct = default) =>
            Task.FromResult(Rows.Where(r => r.TrackUniqueHash == hash).ToList());
        public Task DeleteAutoGeneratedByTrackIdAsync(string hash, CancellationToken ct = default) { Rows.RemoveAll(r => r.TrackUniqueHash == hash && r.IsAutoGenerated); return Task.CompletedTask; }
        public Task DeleteAllByTrackIdAsync(string hash, CancellationToken ct = default) { Rows.RemoveAll(r => r.TrackUniqueHash == hash); return Task.CompletedTask; }
    }

    private sealed class Audio : ICueAudition
    {
        public double PositionSeconds { get; set; }
        public bool IsPlaying { get; set; }
        public readonly List<double> Plays = new();
        public int Stops;
        public void PlayFrom(double seconds) { Plays.Add(seconds); IsPlaying = true; }
        public void Stop() { Stops++; IsPlaying = false; }
    }

    private static (CueEditorSession Session, Store Store, Audio Audio) Create(IEnumerable<CuePointEntity>? rows = null, bool auditionAfterEdits = false)
    {
        var store = new Store();
        if (rows != null) store.Rows.AddRange(rows);
        var audio = new Audio();
        var session = new CueEditorSession(store, audio) { AuditionAfterEdits = auditionAfterEdits, EditorName = "Test" };
        session.Load(new CueTrackInfo(Hash, "Title", "C:/music/s.flac", 120, 0, 300), store.Rows.ToList());
        return (session, store, audio);
    }

    private static CuePointEntity Row(double t, CuePointType type, string label, bool auto = true, int slot = -1) => new()
    {
        TrackUniqueHash = Hash, TimestampInSeconds = t, Type = type, Label = label, IsAutoGenerated = auto, SlotIndex = slot, Color = "#FFFFFF",
    };

    // ── Section markers: set / move / snap ─────────────────────────────────────────

    [Fact]
    public void IntroEnd_AtPlayhead_SnapsToTheBar_IsAMemoryCue_AndThereIsOnlyOne()
    {
        var (s, _, audio) = Create();
        audio.PositionSeconds = 61.3;
        s.SetIntroEndAtPlayheadCommand.Execute().Subscribe();

        var marker = Assert.Single(s.Cues, c => c.Role == CueRole.IntroEnd);
        Assert.Equal(62.0, marker.Timestamp, 6);                // bar 32 (2 s bars), not a beat
        Assert.Equal(SectionMarkers.IntroEndName, marker.Name);
        Assert.Equal(-1, marker.SlotIndex);                      // never takes a hot cue pad
        Assert.Equal(CueSource.User, marker.Source);
        Assert.True(s.HasIntroRegion);
        Assert.Equal(0, s.IntroRegionStart, 6);
        Assert.Equal(62, s.IntroRegionEnd, 6);
        Assert.True(s.IsDirty);

        audio.PositionSeconds = 70.9;                            // setting it again moves the one marker
        s.SetIntroEndAtPlayheadCommand.Execute().Subscribe();
        Assert.Single(s.Cues, c => c.Role == CueRole.IntroEnd);
        Assert.Equal(70.0, s.IntroEndCue!.Timestamp, 6);

        s.UndoCommand.Execute().Subscribe();
        Assert.Equal(62.0, s.IntroEndCue!.Timestamp, 6);
    }

    [Fact]
    public void Outro_RunsToTheEndOfTheTrack_AndMustStartAfterTheIntroEnds()
    {
        var (s, _, _) = Create();
        s.SetIntroEndAtCommand.Execute(64).Subscribe();
        s.SetOutroStartAtCommand.Execute(40).Subscribe();       // before the intro end: refused

        Assert.Null(s.OutroStartCue);
        Assert.True(s.IsStatusError);

        s.SetOutroStartAtCommand.Execute(231.2).Subscribe();
        Assert.Equal(232.0, s.OutroStartCue!.Timestamp, 6);
        Assert.Equal(SectionMarkers.OutroName, s.OutroStartCue.Name);
        Assert.Equal(232, s.OutroRegionStart, 6);
        Assert.Equal(300, s.OutroRegionEnd, 6);
        Assert.Contains("Outro starts at 3:52 (bar 117)", s.StatusText);
    }

    [Fact]
    public void IntroRegion_StartsAtTheIntroCue_WhenThereIsOne()
    {
        var (s, _, _) = Create(new[] { Row(4, CuePointType.Intro, "Intro") });
        s.SetIntroEndAtCommand.Execute(64).Subscribe();
        Assert.Equal(4, s.IntroRegionStart, 6);
    }

    [Fact]
    public void SnapOff_PlacesTheMarkerExactly()
    {
        var (s, _, _) = Create();
        s.SnapToGrid = false;
        s.SetOutroStartAtCommand.Execute(231.37).Subscribe();
        Assert.Equal(231.37, s.OutroStartCue!.Timestamp, 6);
    }

    [Fact]
    public void DraggingAMarker_MovesItsRegion()
    {
        var (s, _, _) = Create();
        s.SetOutroStartAtCommand.Execute(232).Subscribe();
        var marker = s.OutroStartCue!;
        marker.Timestamp = 240;                                  // the waveform moves it in place…
        s.CueUpdatedCommand.Execute(marker).Subscribe();         // …and reports on release

        Assert.Equal(240, s.OutroRegionStart, 6);
        Assert.Contains("Moved", s.StatusText);
    }

    [Fact]
    public void ChoosingTheRole_InTheInspector_KeepsOneMarkerPerSection()
    {
        var (s, _, _) = Create();
        s.SetIntroEndAtCommand.Execute(64).Subscribe();
        s.AddCueAtCommand.Execute(80).Subscribe();
        s.SelectedCueRole = CueRole.IntroEnd;

        Assert.Single(s.Cues, c => c.Role == CueRole.IntroEnd);
        Assert.Equal(80, s.IntroEndCue!.Timestamp, 6);
    }

    // ── Persistence + export ───────────────────────────────────────────────────────

    [Fact]
    public async Task Markers_SaveAsTheirOwnTypes_AndReloadAsSectionRoles()
    {
        var (s, store, _) = Create();
        s.SetIntroEndAtCommand.Execute(64).Subscribe();
        s.SetOutroStartAtCommand.Execute(232).Subscribe();
        Assert.True(await s.SaveAsync());

        Assert.Contains(store.Rows, r => r.Type == CuePointType.IntroEnd && r.Label == "Intro end" && r.SlotIndex == -1 && !r.IsAutoGenerated);
        Assert.Contains(store.Rows, r => r.Type == CuePointType.OutroStart && r.Label == "Outro");
        Assert.Equal(6, (int)CuePointType.IntroEnd);   // stored as integers: no schema change
        Assert.Equal(7, (int)CuePointType.OutroStart);

        var (reloaded, _, _) = Create(store.Rows.ToList());
        Assert.Equal(64, reloaded.IntroEndCue!.Timestamp, 6);
        Assert.Equal(232, reloaded.OutroStartCue!.Timestamp, 6);
    }

    [Fact]
    public void RoleTypeMapping_RoundTripsTheSectionMarkers()
    {
        foreach (var role in new[] { CueRole.IntroEnd, CueRole.OutroStart, CueRole.Drop, CueRole.Intro, CueRole.Outro })
            Assert.Equal(role, OrbitCue.RoleFromType(OrbitCue.TypeFromRole(role)));
        Assert.Equal("Intro end", SectionMarkers.ExportName(CueRole.IntroEnd));
        Assert.Equal("Outro", SectionMarkers.ExportName(CueRole.OutroStart));
        Assert.Null(SectionMarkers.ExportName(CueRole.Outro));
    }

    // ── Suggestions from analysis ──────────────────────────────────────────────────

    private static List<PhraseSegment> Phrases(params (string Label, float Start, float Duration)[] parts) =>
        parts.Select(p => new PhraseSegment { Label = p.Label, Start = p.Start, Duration = p.Duration }).ToList();

    [Fact]
    public void Suggest_UsesTheIntroAndOutroPhrases()
    {
        var phrases = Phrases(("Intro", 0, 32), ("Build", 32, 16), ("Drop", 48, 64), ("Breakdown", 112, 32), ("Drop", 144, 64), ("Outro", 208, 92));
        var drops = new[] { new OrbitCue { Role = CueRole.Drop, Timestamp = 48 }, new OrbitCue { Role = CueRole.Drop, Timestamp = 144 } };

        var s = SectionMarkers.Suggest(phrases, drops, 120, 0, 300);

        Assert.Equal(32, s.IntroEnd!.Value, 6);
        Assert.Equal("end of the intro phrase", s.IntroEndReason);
        Assert.Equal(208, s.OutroStart!.Value, 6);
        Assert.Equal("start of the outro phrase", s.OutroStartReason);
    }

    [Fact]
    public void Suggest_WithoutAnOutroPhrase_TakesThePhraseBoundaryAfterTheLastDropsMainSection()
    {
        var phrases = Phrases(("Intro", 0, 32), ("Drop", 32, 64), ("Breakdown", 96, 48), ("Drop", 144, 32), ("Drop", 176, 32), ("Breakdown", 208, 92));
        var drops = new[] { new OrbitCue { Role = CueRole.Drop, Timestamp = 32 }, new OrbitCue { Role = CueRole.Drop, Timestamp = 144.4 } };

        var s = SectionMarkers.Suggest(phrases, drops, 120, 0, 300);

        Assert.Equal(208, s.OutroStart!.Value, 6);   // end of the drop run starting at the last drop
        Assert.Equal("phrase boundary after the last drop's main section", s.OutroStartReason);
    }

    [Fact]
    public void Suggest_WithOnlyDrops_UsesTheFirstDropAndThe32BarRule()
    {
        var drops = new[] { new OrbitCue { Role = CueRole.Drop, Timestamp = 64 }, new OrbitCue { Role = CueRole.Drop, Timestamp = 160 } };
        var s = SectionMarkers.Suggest(null, drops, 120, 0, 300);

        Assert.Equal(64, s.IntroEnd!.Value, 6);
        Assert.Equal(224, s.OutroStart!.Value, 6);   // last drop + 32 bars of 2 s
    }

    [Fact]
    public void Suggest_WithNothingToGoOn_SuggestsNothing()
    {
        Assert.True(SectionMarkers.Suggest(null, Array.Empty<OrbitCue>(), 120, 0, 300).IsEmpty);
    }

    [Fact]
    public void Session_OffersTheSuggestion_AndUseSuggestionPlacesBothInOneUndoStep()
    {
        var (s, _, _) = Create(new[] { Row(64, CuePointType.Drop, "[DROP 1]"), Row(160, CuePointType.Drop, "[DROP 2]") });
        s.SetStructureHints(Phrases(("Intro", 0, 32.3f), ("Drop", 64, 64)));

        Assert.True(s.HasSectionSuggestion);
        Assert.Equal(32, s.SuggestedIntroEnd!.Value, 6);        // phrase end snapped to the bar
        Assert.Contains("intro ends 0:32 (bar 17)", s.SectionSuggestionText);

        s.UseSectionSuggestionCommand.Execute().Subscribe();
        Assert.Equal(32, s.IntroEndCue!.Timestamp, 6);
        Assert.Equal(224, s.OutroStartCue!.Timestamp, 6);
        Assert.False(s.HasSectionSuggestion);
        Assert.Equal("Intro to 0:32 (bar 17) · outro from 3:44 (bar 113)", s.SectionSummary);

        s.UndoCommand.Execute().Subscribe();
        Assert.Null(s.IntroEndCue);
        Assert.Null(s.OutroStartCue);
        Assert.True(s.HasSectionSuggestion);
    }

    // ── Click to prelisten ─────────────────────────────────────────────────────────

    [Fact]
    public void ClickingACue_SelectsIt_AndPlaysFromExactlyTheCue_WithoutTouchingIt()
    {
        var (s, _, audio) = Create(new[] { Row(33.37, CuePointType.Drop, "Drop") });
        var cue = s.Cues.Single();

        s.PrelistenCueCommand.Execute(cue).Subscribe();

        Assert.Same(cue, s.SelectedCue);
        Assert.Equal(new[] { 33.37 }, audio.Plays);              // the exact cue time, no pre-roll, no snapping
        Assert.Equal(33.37, cue.Timestamp, 9);
        Assert.Equal(CueSource.Auto, cue.Source);
        Assert.False(s.IsDirty);
        Assert.False(s.CanUndo);
    }

    [Fact]
    public void ClickingThePlayingCueAgain_Stops_AndSpaceStopsToo()
    {
        var (s, _, audio) = Create(new[] { Row(20, CuePointType.Intro, "Intro"), Row(60, CuePointType.Drop, "Drop") });
        var a = s.Cues[0];
        var b = s.Cues[1];

        s.PrelistenCue(a);
        s.PrelistenCue(a);                                       // same flag again: stop
        Assert.Equal(1, audio.Stops);
        Assert.False(audio.IsPlaying);
        Assert.Null(s.PrelisteningCue);

        s.PrelistenCue(a);
        s.PrelistenCue(b);                                       // another flag: play from there
        Assert.Equal(new[] { 20.0, 20.0, 60.0 }, audio.Plays);
        Assert.Same(b, s.PrelisteningCue);

        Assert.True(s.StopPrelisten());                          // Space
        Assert.Equal(2, audio.Stops);
        Assert.False(s.StopPrelisten());                         // nothing left: Space falls through to play/pause
    }

    [Fact]
    public void DraggingACue_MovesIt_WithoutAPrelisten()
    {
        var (s, _, audio) = Create(new[] { Row(40, CuePointType.Drop, "Drop", auto: false) });
        var cue = s.Cues.Single();

        cue.Timestamp = 44;                                      // a drag past the threshold moved it
        s.CueUpdatedCommand.Execute(cue).Subscribe();

        Assert.Equal(44, cue.Timestamp, 6);
        Assert.Empty(audio.Plays);                               // Cue Forge: no audition on drags
        Assert.Null(s.PrelisteningCue);
        Assert.True(s.IsDirty);
    }

    [Fact]
    public void MarkerGesture_SmallMovementIsAClick_PastTheThresholdIsADrag()
    {
        var cue = new OrbitCue { Timestamp = 10 };
        var g = new MarkerGesture<OrbitCue>();

        g.Press(cue, 100);
        Assert.False(g.Move(100 + MarkerGesture<OrbitCue>.DragThresholdPixels - 1));
        var click = g.Release();
        Assert.Equal(MarkerGestureResult.Click, click.Result);
        Assert.Same(cue, click.Target);

        g.Press(cue, 100);
        Assert.True(g.Move(100 - MarkerGesture<OrbitCue>.DragThresholdPixels));  // starts the drag once…
        Assert.False(g.Move(90));                                                 // …and only once
        Assert.Equal(MarkerGestureResult.Drag, g.Release().Result);

        g.Press(cue, 100);
        g.Cancel();
        Assert.Equal(MarkerGestureResult.None, g.Release().Result);
    }
}
