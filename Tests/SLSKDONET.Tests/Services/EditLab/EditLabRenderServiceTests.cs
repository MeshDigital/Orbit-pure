using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using NAudio.Wave;
using SLSKDONET.Data;
using SLSKDONET.Data.Entities;
using SLSKDONET.Models;
using SLSKDONET.Models.EditLab;
using SLSKDONET.Services;
using SLSKDONET.Services.EditLab;
using Xunit;

namespace SLSKDONET.Tests.Services.EditLab;

/// <summary>Render-to-library against the isolated test database (ORBIT_DB_PATH).</summary>
public sealed class EditLabRenderServiceTests : IDisposable
{
    private readonly string _dir = Path.Combine(Path.GetTempPath(), "orbit-editlab-library", Guid.NewGuid().ToString("N"));
    private readonly CapturingBus _bus = new();
    private readonly CapturingCues _cues = new();

    public EditLabRenderServiceTests() => Directory.CreateDirectory(_dir);

    public void Dispose()
    {
        try { Directory.Delete(_dir, recursive: true); }
        catch (IOException) { /* temp dir */ }
    }

    private EditProject Project(string artistTitleSeed)
    {
        var path = Path.Combine(_dir, $"{artistTitleSeed}.wav");
        using (var w = new WaveFileWriter(path, WaveFormat.CreateIeeeFloatWaveFormat(44100, 2)))
            for (long f = 0; f < 44100L * 12; f++) { float s = 0.2f * (float)Math.Sin(2 * Math.PI * 220 * f / 44100); w.WriteSamples(new[] { s, s }, 0, 2); }

        var p = new EditProject { Name = "Intro edit", Bpm = 120, Key = "8A", BaseTrackHash = "src-" + artistTitleSeed };
        p.Sources.Add(new EditSource { TrackHash = "src-" + artistTitleSeed, Title = "Base " + artistTitleSeed, Artist = "Test Artist", Bpm = 120, FilePath = path, SampleRate = 44100, DurationSeconds = 12 });
        p.Lanes.Add(new EditLane
        {
            Clips =
            {
                new EditClip { SourceHash = "src-" + artistTitleSeed, StartBar = 0, LengthBars = 2 },
                new EditClip { SourceHash = "src-" + artistTitleSeed, StartBar = 2, LengthBars = 2, SourceInSeconds = 1 },
            },
        });
        return p;
    }

    private EditLabRenderService Service() =>
        new(new PlainSources(), null, _bus, _cues, outputDirectoryOverride: Path.Combine(_dir, "renders"));

    [Fact]
    public async Task Render_AddsATrackWithProvenance_QueuesAnalysis_AndWritesCues()
    {
        var project = Project(Guid.NewGuid().ToString("N")[..8]);
        var outcome = await Service().RenderToLibraryAsync(new EditRenderRequest(project, EditRenderFormat.Wav, false, WriteCues: true), null, CancellationToken.None);

        Assert.True(File.Exists(outcome.FilePath));
        Assert.EndsWith("(ORBIT Edit).wav", outcome.FilePath, StringComparison.Ordinal);
        Assert.Equal(8.0, outcome.Result.DurationSeconds, 3);

        await using var db = new AppDbContext();
        var entry = await db.LibraryEntries.AsNoTracking().SingleAsync(e => e.UniqueHash == outcome.TrackHash);
        Assert.Equal($"{project.Sources[0].Title} (ORBIT Edit)", entry.Title);
        Assert.Equal("Test Artist", entry.Artist);
        Assert.Equal(120, entry.BPM);
        Assert.Equal(120, entry.TagBPM);
        Assert.Equal("8A", entry.MusicalKey);
        Assert.Equal(TrackAvailabilityState.LocalUnanalyzed, entry.AvailabilityState);
        Assert.Equal($"orbit-edit-lab;project={project.Id:N};sources={project.Sources[0].TrackHash}", entry.SourceProvenance);

        Assert.Contains(_bus.Published.OfType<TrackAnalysisRequestedEvent>(), e => e.TrackGlobalId == outcome.TrackHash);
        var cue = Assert.Single(_cues.Created);
        Assert.Equal(4.0, cue.TimestampInSeconds, 6); // the second clip, bar 3 at 120 BPM
        Assert.False(cue.IsAutoGenerated);
        Assert.Equal(1, outcome.CuesWritten);

        using var tags = TagLib.File.Create(outcome.FilePath);
        Assert.Equal(120u, tags.Tag.BeatsPerMinute);
        Assert.Equal(entry.Title, tags.Tag.Title);
    }

    [Fact]
    public async Task RenderingTwice_GetsANumberedTitle()
    {
        var project = Project(Guid.NewGuid().ToString("N")[..8]);
        var service = Service();
        var first = await service.RenderToLibraryAsync(new EditRenderRequest(project, EditRenderFormat.Wav, false, false), null, CancellationToken.None);
        var second = await service.RenderToLibraryAsync(new EditRenderRequest(project, EditRenderFormat.Wav, false, false), null, CancellationToken.None);
        Assert.NotEqual(first.TrackHash, second.TrackHash);
        Assert.EndsWith("(ORBIT Edit) 2", second.Title, StringComparison.Ordinal);
    }

    [Fact]
    public async Task LoopRegionOnly_RendersTheRegion()
    {
        var project = Project(Guid.NewGuid().ToString("N")[..8]);
        project.LoopStartBar = 1;
        project.LoopEndBar = 3;
        var outcome = await Service().RenderToLibraryAsync(new EditRenderRequest(project, EditRenderFormat.Wav, true, true), null, CancellationToken.None);
        Assert.Equal(4.0, outcome.Result.DurationSeconds, 3);
        Assert.Contains("(ORBIT Edit loop)", outcome.Title, StringComparison.Ordinal);
        Assert.Equal(2.0, Assert.Single(_cues.Created).TimestampInSeconds, 6); // bar 3 is 2 s into the region
    }

    [Fact]
    public async Task MissingStems_FailWithoutAddingAnything()
    {
        var project = Project(Guid.NewGuid().ToString("N")[..8]);
        project.Lanes[0].Clips[0].Stem = EditStem.Vocals;
        var ex = await Assert.ThrowsAsync<InvalidOperationException>(() =>
            Service().RenderToLibraryAsync(new EditRenderRequest(project, EditRenderFormat.Wav, false, false), null, CancellationToken.None));
        Assert.Contains("isn't separated", ex.Message, StringComparison.Ordinal);
        Assert.Empty(_bus.Published);
        Assert.False(Directory.Exists(Path.Combine(_dir, "renders")) && Directory.EnumerateFiles(Path.Combine(_dir, "renders")).Any());
    }

    private sealed class PlainSources : EditLabSourceService
    {
        public PlainSources() : base(null, null, null) { }
        public override string? ResolvePlayablePath(EditSource source, EditStem stem) => EditRenderPlan.DefaultAudioPath(source, stem);
    }

    private sealed class CapturingBus : IEventBus
    {
        public readonly List<object> Published = new();
        public IObservable<T> GetEvent<T>() => System.Reactive.Linq.Observable.Empty<T>();
        public void Publish<T>(T eventData) { if (eventData != null) Published.Add(eventData); }
    }

    private sealed class CapturingCues : ICuePointService
    {
        public readonly List<CuePointEntity> Created = new();
        public Task CreateManyAsync(IEnumerable<CuePointEntity> cuePoints, CancellationToken cancellationToken = default) { Created.AddRange(cuePoints); return Task.CompletedTask; }
        public Task<List<CuePointEntity>> GetByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) => Task.FromResult(Created.Where(c => c.TrackUniqueHash == trackUniqueHash).ToList());
        public Task DeleteAutoGeneratedByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) => Task.CompletedTask;
        public Task DeleteAllByTrackIdAsync(string trackUniqueHash, CancellationToken cancellationToken = default) => Task.CompletedTask;
    }
}
