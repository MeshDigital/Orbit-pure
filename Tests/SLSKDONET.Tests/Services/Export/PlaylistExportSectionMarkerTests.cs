using System;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using System.Xml.Linq;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging.Abstractions;
using SLSKDONET.Data;
using SLSKDONET.Data.Entities;
using SLSKDONET.Models;
using SLSKDONET.Services.Library;
using Xunit;

namespace SLSKDONET.Tests.Services.Export;

/// <summary>The Intro end / Outro section markers export to Rekordbox as memory cues with fixed names.</summary>
public class PlaylistExportSectionMarkerTests : IDisposable
{
    private readonly string _tempDir = Path.Combine(Path.GetTempPath(), $"ORBIT_ExportSections_{Guid.NewGuid():N}");

    public PlaylistExportSectionMarkerTests() => Directory.CreateDirectory(_tempDir);

    public void Dispose()
    {
        if (Directory.Exists(_tempDir)) Directory.Delete(_tempDir, recursive: true);
    }

    [Fact]
    public async Task SectionMarkers_ExportAsNamedMemoryCues_WithoutTakingAPad()
    {
        var options = new DbContextOptionsBuilder<AppDbContext>().UseInMemoryDatabase($"ExportSections_{Guid.NewGuid():N}").Options;
        var factory = new Factory(options);
        const string hash = "hash-sections";
        await using (var db = factory.CreateDbContext())
        {
            db.CuePoints.AddRange(
                new CuePointEntity { TrackUniqueHash = hash, TimestampInSeconds = 10, Type = CuePointType.Drop, Label = "[DROP 1]", SlotIndex = 2, IsAutoGenerated = false },
                new CuePointEntity { TrackUniqueHash = hash, TimestampInSeconds = 62, Type = CuePointType.IntroEnd, Label = "my intro", SlotIndex = -1, IsAutoGenerated = false, Color = "#00CCFF" },
                new CuePointEntity { TrackUniqueHash = hash, TimestampInSeconds = 232, Type = CuePointType.OutroStart, Label = "Outro", SlotIndex = -1, IsAutoGenerated = false, Color = "#0044FF" });
            await db.SaveChangesAsync();
        }

        var file = Path.Combine(_tempDir, "track.mp3");
        File.WriteAllText(file, "fake audio");
        var output = Path.Combine(_tempDir, "out.xml");
        var track = new PlaylistTrack { Id = Guid.NewGuid(), Title = "T", Artist = "A", ResolvedFilePath = file, TrackUniqueHash = hash };

        var service = new PlaylistExportService(NullLogger<PlaylistExportService>.Instance, factory, new SLSKDONET.Tests.Helpers.FakeFileWriteService());
        await service.ExportToRekordboxXmlAsync("Sections", new[] { track }, output);

        var marks = XDocument.Load(output).Descendants("TRACK").Single(e => e.Attribute("Location") != null).Elements("POSITION_MARK").ToList();
        var intro = Assert.Single(marks, m => m.Attribute("Start")?.Value == "62.000");
        Assert.Equal("Intro end", intro.Attribute("Name")?.Value);
        Assert.Equal("-1", intro.Attribute("Num")?.Value);
        Assert.Equal("0", intro.Attribute("Type")?.Value);
        var outro = Assert.Single(marks, m => m.Attribute("Start")?.Value == "232.000");
        Assert.Equal("Outro", outro.Attribute("Name")?.Value);
        Assert.Equal("-1", outro.Attribute("Num")?.Value);
        // The drop keeps its pad; the markers didn't take one.
        Assert.Contains(marks, m => m.Attribute("Start")?.Value == "10.000" && m.Attribute("Num")?.Value == "2");
    }

    private sealed class Factory : IDbContextFactory<AppDbContext>
    {
        private readonly DbContextOptions<AppDbContext> _options;
        public Factory(DbContextOptions<AppDbContext> options) => _options = options;
        public AppDbContext CreateDbContext() => new(_options);
    }
}
