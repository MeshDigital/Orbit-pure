    private static async Task<TestDbContextFactory> CreateFreshFactoryAsync()
    {
        var factory = new TestDbContextFactory();
        await using var db = await factory.CreateDbContextAsync();
        await db.Database.EnsureCreatedAsync();
        return factory;
    }

    private static AudioFeaturesEntity MakeReadyFeatures(string hash) => new()
    {
        TrackUniqueHash = hash,
        Bpm = 174f,
        BeatGridJson = "[0.0,0.345,0.69]",
        LoudnessLUFS = -8.5f,
        WaveformBlob = new byte[] { 1, 2, 3, 4 },
        StructuralVersion = 1,
        TrackDuration = 240f,
    };

    private static List<CuePointEntity> MakeReadyCues(string hash) => new()
    {
        new CuePointEntity { TrackUniqueHash = hash, TimestampInSeconds = 8.0, Type = CuePointType.Intro, Label = "Intro", IsAutoGenerated = true },
        new CuePointEntity { TrackUniqueHash = hash, TimestampInSeconds = 210.0, Type = CuePointType.Outro, Label = "Outro", IsAutoGenerated = true },
    };

    private static PlaylistTrackEntity MakePlaylistTrack(Guid playlistId, string hash, string title, int sortOrder) => new()
    {
        Id = Guid.NewGuid(),
        PlaylistId = playlistId,
        TrackUniqueHash = hash,
        Artist = "Artist",
        Title = title,
        ResolvedFilePath = $"C:/fake/{hash}.mp3",
        Status = TrackStatus.Downloaded,
        SortOrder = sortOrder,
    };

    // ── TrackMixReadinessEvaluator ────────────────────────────────────────────

    [Fact]
    public void Readiness_AllCriteriaPresent_IsReady()
    {
        var r = TrackMixReadinessEvaluator.Evaluate(MakeReadyFeatures("t1"), MakeReadyCues("t1"));
        Assert.True(r.IsReady);
        Assert.Empty(r.MissingItems);
        Assert.Equal(AnalysisEngine.None, r.MissingAudioEngines);
        Assert.False(r.NeedsCues);
    }

    [Theory]
    [InlineData("bpm")]
    [InlineData("grid")]
    [InlineData("entry")]
    [InlineData("exit")]
    [InlineData("lufs")]
    public void Readiness_MissingAnySingleCriterion_IsNotReady(string missing)
    {
        var features = MakeReadyFeatures("t1");
        var cues = MakeReadyCues("t1");

        switch (missing)
        {
            case "bpm": features.Bpm = 0; break;
            case "grid": features.BeatGridJson = "[]"; break;
            case "entry": cues.RemoveAll(c => c.Type == CuePointType.Intro); break;
            case "exit": cues.RemoveAll(c => c.Type == CuePointType.Outro); break;
            case "lufs": features.LoudnessLUFS = 0; break;
        }

        var r = TrackMixReadinessEvaluator.Evaluate(features, cues);
        Assert.False(r.IsReady);
        Assert.NotEmpty(r.MissingItems);
    }

    // ── #524 FO2a: PlaylistPrepService.PrepareAsync ───────────────────────────

    [Fact]
    public async Task PrepareAsync_AlreadyReadyTrack_IsSkippedCompletely()
    {
        using var scope = new FreshDatabaseScope();
        var factory = await CreateFreshFactoryAsync();
        var playlistId = Guid.NewGuid();

        await using (var db = await factory.CreateDbContextAsync())
        {
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, "ready-1", "Ready Track", 0));
            db.AudioFeatures.Add(MakeReadyFeatures("ready-1"));
            db.CuePoints.AddRange(MakeReadyCues("ready-1"));
            await db.SaveChangesAsync();
        }

        var audioCalls = new List<(string Hash, AnalysisEngine Engines)>();
        var cueCalls = new List<(string Hash, bool NeedsStructure)>();

        var svc = new PlaylistPrepService(
            factory,
            audioAnalysisOverride: (_, hash, engines, _) => { audioCalls.Add((hash, engines)); return Task.FromResult(true); },
            structureAndCuesOverride: (hash, needsStructure, _) => { cueCalls.Add((hash, needsStructure)); return Task.FromResult(true); },
            eligibilityOverride: _ => true);

        var result = await svc.PrepareAsync(playlistId);

        Assert.False(result.WasCancelled);
        Assert.Equal(1, result.TotalEligible);
        Assert.Equal(1, result.Skipped);
        Assert.Equal(0, result.Prepared);
        Assert.Empty(audioCalls);
        Assert.Empty(cueCalls);
    }

    [Fact]
    public async Task PrepareAsync_PartlyDoneTracks_RunOnlyMissingSteps()
    {
        using var scope = new FreshDatabaseScope();
        var factory = await CreateFreshFactoryAsync();
        var playlistId = Guid.NewGuid();

        await using (var db = await factory.CreateDbContextAsync())
        {
            // Track 1: has everything except LUFS -> should run ONLY AnalysisEngine.Loudness, no cue step
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, "no-lufs", "Needs LUFS", 0));
            var noLufs = MakeReadyFeatures("no-lufs");
            noLufs.LoudnessLUFS = 0;
            db.AudioFeatures.Add(noLufs);
            db.CuePoints.AddRange(MakeReadyCues("no-lufs"));

            // Track 2: has features + structure, missing cues -> should run ONLY cues (needsStructure=false), no audio step
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, "no-cues", "Needs Cues", 1));
            db.AudioFeatures.Add(MakeReadyFeatures("no-cues"));

            // Track 3: brand new (no AudioFeatures) -> should run full Pipeline + structure/cues
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, "fresh", "Fresh Track", 2));

            await db.SaveChangesAsync();
        }

        var audioCalls = new List<(string Hash, AnalysisEngine Engines)>();
        var cueCalls = new List<(string Hash, bool NeedsStructure)>();

        var svc = new PlaylistPrepService(
            factory,
            audioAnalysisOverride: (_, hash, engines, _) => { audioCalls.Add((hash, engines)); return Task.FromResult(true); },
            structureAndCuesOverride: (hash, needsStructure, _) => { cueCalls.Add((hash, needsStructure)); return Task.FromResult(true); },
            eligibilityOverride: _ => true);

        var result = await svc.PrepareAsync(playlistId);

        Assert.Equal(3, result.TotalEligible);
        Assert.Equal(3, result.Prepared);
        Assert.Equal(0, result.Skipped);
        Assert.Equal(0, result.Failed);

        // Track 1: Loudness only
        Assert.Contains(audioCalls, c => c.Hash == "no-lufs" && c.Engines == AnalysisEngine.Loudness);
        Assert.DoesNotContain(cueCalls, c => c.Hash == "no-lufs");

        // Track 2: Cues only (structure already exists)
        Assert.DoesNotContain(audioCalls, c => c.Hash == "no-cues");
        Assert.Contains(cueCalls, c => c.Hash == "no-cues" && !c.NeedsStructure);

        // Track 3: Full pipeline + structure/cues
        Assert.Contains(audioCalls, c => c.Hash == "fresh" && c.Engines == AnalysisEngine.Pipeline);
        Assert.Contains(cueCalls, c => c.Hash == "fresh" && c.NeedsStructure);
    }

    [Fact]
    public async Task PrepareAsync_Cancellation_StopsBetweenTracks()
    {
        using var scope = new FreshDatabaseScope();
        var factory = await CreateFreshFactoryAsync();
        var playlistId = Guid.NewGuid();

        await using (var db = await factory.CreateDbContextAsync())
        {
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, "t1", "Track 1", 0));
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, "t2", "Track 2", 1));
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, "t3", "Track 3", 2));
            await db.SaveChangesAsync();
        }

        using var cts = new CancellationTokenSource();
        var processed = new List<string>();

        var svc = new PlaylistPrepService(
            factory,
            audioAnalysisOverride: (_, hash, _, _) =>
            {
                processed.Add(hash);
                return Task.FromResult(true);
            },
            structureAndCuesOverride: (hash, _, _) =>
            {
                if (hash == "t1") cts.Cancel();
                return Task.FromResult(true);
            },
            eligibilityOverride: _ => true);

        var result = await svc.PrepareAsync(playlistId, cancellationToken: cts.Token);

        Assert.True(result.WasCancelled);
        Assert.Single(processed);
        Assert.Equal("t1", processed[0]);
        Assert.Equal(1, result.Prepared);
    }

    // ── #525 FO2b: Prep never touches user or imported Rekordbox cues ─────────

    [Fact]
    public async Task ReplaceAutoCues_WithOneUserCue_KeepsUserCueUnchangedAndAddsMissingAutoCues()
    {
        using var scope = new FreshDatabaseScope();
        var factory = await CreateFreshFactoryAsync();
        const string hash = "user-cue-track";

        var userMixIn = new CuePointEntity
        {
            TrackUniqueHash = hash,
            TimestampInSeconds = 16.25,
            Type = CuePointType.MixIn,
            Label = "My Mix In",
            Color = "#FF00AA",
            SlotIndex = 0, // Pad A
            IsAutoGenerated = false,
        };

        await using (var db = await factory.CreateDbContextAsync())
        {
            db.CuePoints.Add(userMixIn);
            await db.SaveChangesAsync();
        }

        var cueGen = new CueGenerationService(factory, logger: NullLogger<CueGenerationService>.Instance);
        var generated = new List<CuePointEntity>
        {
            // Should be skipped because user already owns MixIn
            new() { TrackUniqueHash = hash, TimestampInSeconds = 12.0, Type = CuePointType.MixIn, Label = "Auto MixIn", SlotIndex = 1, IsAutoGenerated = true },
            // Claims Pad A (Slot 0) which user owns -> should be demoted to memory cue (-1)
            new() { TrackUniqueHash = hash, TimestampInSeconds = 64.0, Type = CuePointType.Drop, Label = "[DROP 1]", SlotIndex = 0, IsAutoGenerated = true },
            // Missing exit cue -> should be added cleanly
            new() { TrackUniqueHash = hash, TimestampInSeconds = 210.0, Type = CuePointType.Outro, Label = "Outro", SlotIndex = 2, IsAutoGenerated = true },
        };

        await cueGen.ReplaceAutoCuesAsync(hash, generated);

        await using (var db = await factory.CreateDbContextAsync())
        {
            var stored = await db.CuePoints.AsNoTracking()
                .Where(c => c.TrackUniqueHash == hash)
                .OrderBy(c => c.TimestampInSeconds)
                .ToListAsync();

            var keptUser = Assert.Single(stored, c => !c.IsAutoGenerated);
            Assert.Equal(userMixIn.Id, keptUser.Id);
            Assert.Equal(16.25, keptUser.TimestampInSeconds);
            Assert.Equal("My Mix In", keptUser.Label);
            Assert.Equal("#FF00AA", keptUser.Color);
            Assert.Equal(0, keptUser.SlotIndex);

            // Auto MixIn was skipped because user MixIn exists
            Assert.DoesNotContain(stored, c => c.IsAutoGenerated && c.Type == CuePointType.MixIn);

            // Auto Drop kept its timestamp but surrendered Pad A to memory cue (-1)
            var autoDrop = Assert.Single(stored, c => c.IsAutoGenerated && c.Type == CuePointType.Drop);
            Assert.Equal(-1, autoDrop.SlotIndex);

            // Missing Outro cue was added
            var autoOutro = Assert.Single(stored, c => c.IsAutoGenerated && c.Type == CuePointType.Outro);
            Assert.Equal(210.0, autoOutro.TimestampInSeconds);
        }
    }

    [Fact]
    public async Task PrepPass_ImportedRekordboxCues_SurviveUnchanged()
    {
        using var scope = new FreshDatabaseScope();
        var factory = await CreateFreshFactoryAsync();
        var playlistId = Guid.NewGuid();
        const string hash = "rb-imported-track";

        var rbTrack = new RekordboxDbTrack(
            Id: "1",
            Path: $"C:/fake/{hash}.mp3",
            Title: "RB Track",
            Artist: "DJ",
            Bpm: 174.0,
            Cues: new List<RekordboxDbCue>
            {
                new(Kind: 1, InMsec: 32000, OutMsec: 0, ColorTableIndex: 1, Comment: "RB Drop"),
                new(Kind: 0, InMsec: 96000, OutMsec: 104000, ColorTableIndex: 2, Comment: "RB Loop"),
            });

        // Import via RekordboxCueImport -> OrbitCue -> CuePointEntity
        var importedOrbitCues = RekordboxCueImport.ToOrbitCues(rbTrack);
        Assert.All(importedOrbitCues, c => Assert.Equal(CueSource.User, c.Source));

        var importedEntities = importedOrbitCues.Select(c => c.ToEntity(hash)).ToList();
        Assert.All(importedEntities, e => Assert.False(e.IsAutoGenerated));

        await using (var db = await factory.CreateDbContextAsync())
        {
            db.PlaylistTracks.Add(MakePlaylistTrack(playlistId, hash, "RB Track", 0));
            db.AudioFeatures.Add(MakeReadyFeatures(hash));
            db.CuePoints.AddRange(importedEntities);
            await db.SaveChangesAsync();
        }

        var cueGen = new CueGenerationService(factory, logger: NullLogger<CueGenerationService>.Instance);
        var svc = new PlaylistPrepService(
            factory,
            audioAnalysisOverride: (_, _, _, _) => Task.FromResult(true),
            structureAndCuesOverride: async (h, _, ct) =>
            {
                await cueGen.ReplaceAutoCuesAsync(h, new List<CuePointEntity>
                {
                    new() { TrackUniqueHash = h, TimestampInSeconds = 8.0, Type = CuePointType.Intro, Label = "Intro", SlotIndex = 0, IsAutoGenerated = true },
                    new() { TrackUniqueHash = h, TimestampInSeconds = 32.2, Type = CuePointType.Drop, Label = "Auto Drop", SlotIndex = 1, IsAutoGenerated = true },
                    new() { TrackUniqueHash = h, TimestampInSeconds = 200.0, Type = CuePointType.Outro, Label = "Outro", SlotIndex = 2, IsAutoGenerated = true },
                }, ct);
                return true;
            },
            eligibilityOverride: _ => true);

        var result = await svc.PrepareAsync(playlistId);
        Assert.Equal(1, result.Prepared);

        await using (var db = await factory.CreateDbContextAsync())
        {
            var stored = await db.CuePoints.AsNoTracking()
                .Where(c => c.TrackUniqueHash == hash)
                .OrderBy(c => c.TimestampInSeconds)
                .ToListAsync();

            // Both Rekordbox cues survived untouched with IsAutoGenerated = false
            var locked = stored.Where(c => !c.IsAutoGenerated).ToList();
            Assert.Equal(2, locked.Count);
            Assert.Contains(locked, c => c.Label == "RB Drop" && Math.Abs(c.TimestampInSeconds - 32.0) < 0.001 && c.SlotIndex == 0);
            Assert.Contains(locked, c => c.Label == "RB Loop" && c.IsLoop && Math.Abs(c.TimestampInSeconds - 96.0) < 0.001);

            // Auto Drop at 32.2s collided with RB Drop at 32.0s and was skipped
            Assert.DoesNotContain(stored, c => c.IsAutoGenerated && c.Label == "Auto Drop");

            // Missing Intro & Outro were added, and Intro surrendered Pad A to memory cue (-1)
            var intro = Assert.Single(stored, c => c.IsAutoGenerated && c.Type == CuePointType.Intro);
            Assert.Equal(-1, intro.SlotIndex);
            Assert.Contains(stored, c => c.IsAutoGenerated && c.Type == CuePointType.Outro);
        }
    }
