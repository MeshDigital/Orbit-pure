using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging.Abstractions;
using SLSKDONET.Data;
using SLSKDONET.Data.Entities;
using SLSKDONET.Models;
using SLSKDONET.Services.AudioAnalysis;
using Xunit;

namespace SLSKDONET.Tests.Services.AudioAnalysis;

/// <summary>
/// The one-time repair of stored auto cues: tracks whose Drop 2 was clamped into the outro get
/// regenerated, every other auto Drop 2 gets its countdowns renamed to [IN2 …], and nothing the
/// user placed is touched. Runs against the isolated test database (ORBIT_DB_PATH).
/// </summary>
public sealed class CueLayoutRepairServiceTests : IDisposable
{
    private readonly string _dir = Path.Combine(Path.GetTempPath(), $"orbit-cue-repair-{Guid.NewGuid():N}");
    private readonly string _late = "late-" + Guid.NewGuid().ToString("N");
    private readonly string _normal = "normal-" + Guid.NewGuid().ToString("N");
    private readonly string _manual = "manual-" + Guid.NewGuid().ToString("N");

    public void Dispose()
    {
        Microsoft.Data.Sqlite.SqliteConnection.ClearAllPools();
        if (Directory.Exists(_dir)) Directory.Delete(_dir, recursive: true);
    }

    private const double Bpm = 150, Bar = 240.0 / Bpm, Duration = 243.2;

    private static CuePointEntity Cue(string hash, double t, string label, CuePointType type, bool auto = true) => new()
    {
        TrackUniqueHash = hash, TimestampInSeconds = t, Label = label, Type = type, IsAutoGenerated = auto,
    };

    private async Task SeedAsync()
    {
        using var db = new AppDbContext();
        foreach (var hash in new[] { _late, _normal, _manual })
        {
            db.LibraryEntries.Add(new LibraryEntryEntity { UniqueHash = hash, Artist = "A", Title = hash, FilePath = $@"C:\music\{hash}.flac", AddedAt = DateTime.UtcNow });
            db.AudioFeatures.Add(new AudioFeaturesEntity { TrackUniqueHash = hash, Bpm = (float)Bpm, TrackDuration = Duration });
        }

        // Flux Pavilion shape: Drop 2 clamped to duration − 8 bars.
        double lateDrop2 = Duration - 8 * Bar;
        db.CuePoints.AddRange(
            Cue(_late, lateDrop2 - 16 * Bar, "[IN -16]", CuePointType.Build),
            Cue(_late, lateDrop2, "[DROP 2]", CuePointType.Drop));

        // A normal track: both drops' countdowns are named [IN -N].
        double drop1 = 32.4, drop2 = 120.4;
        db.CuePoints.AddRange(
            Cue(_normal, drop1 - 16 * Bar, "[IN -16]", CuePointType.Build),
            Cue(_normal, drop1 - 8 * Bar, "[IN -8]", CuePointType.Build),
            Cue(_normal, drop1, "[DROP 1]", CuePointType.Drop),
            Cue(_normal, drop2 - 16 * Bar, "[IN -16]", CuePointType.Build),
            Cue(_normal, drop2 - 8 * Bar, "[IN -8]", CuePointType.Build),
            Cue(_normal, drop2, "[DROP 2]", CuePointType.Drop),
            Cue(_normal, drop2 - 8 * Bar, "[IN -8]", CuePointType.Build, auto: false)); // yours: never renamed

        // The user placed a drop here: the track is theirs, nothing is regenerated or renamed.
        db.CuePoints.AddRange(
            Cue(_manual, Duration - 4 * Bar, "[DROP 2]", CuePointType.Drop),
            Cue(_manual, 60, "My drop", CuePointType.Drop, auto: false));
        await db.SaveChangesAsync();
    }

    [Fact]
    public async Task Run_RegeneratesLateDrops_RenamesDrop2Countdowns_AndSkipsUserTracks()
    {
        await SeedAsync();
        var regenerated = new List<string>();
        var service = new CueLayoutRepairService(NullLogger<CueLayoutRepairService>.Instance)
        {
            DataDirectory = _dir,
            OnlyTracks = new[] { _late, _normal, _manual },
            Regenerate = (hash, _) => { regenerated.Add(hash); return Task.FromResult(true); },
        };

        var summary = await service.RunAsync();

        Assert.Equal(new[] { _late }, regenerated);
        Assert.Equal(2, summary.CountdownsRenamed);

        using var db = new AppDbContext();
        var normal = await db.CuePoints.AsNoTracking().Where(c => c.TrackUniqueHash == _normal).ToListAsync();
        Assert.Equal(2, normal.Count(c => c.IsAutoGenerated && c.Label == "[IN -16]" || c.IsAutoGenerated && c.Label == "[IN -8]")); // Drop 1's
        Assert.Contains(normal, c => c.Label == "[IN2 -16]");
        Assert.Contains(normal, c => c.Label == "[IN2 -8]" && c.IsAutoGenerated);
        Assert.Contains(normal, c => c.Label == "[IN -8]" && !c.IsAutoGenerated); // your cue kept its name

        Assert.True(Directory.GetFiles(_dir, "library.db.bak-*").Length == 1, "backup written before changing anything");

        // Runs once.
        regenerated.Clear();
        Assert.Same(CueLayoutRepairSummary.AlreadyDone, await service.RunAsync());
        Assert.Empty(regenerated);
    }
}
