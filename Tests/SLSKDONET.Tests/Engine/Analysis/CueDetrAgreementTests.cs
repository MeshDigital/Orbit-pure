    [Theory]
    [InlineData(64.0, 64.0, 120.0, true)]    // exact match
    [InlineData(64.0, 64.5, 120.0, true)]    // exact +1 beat edge (0.5 s at 120 BPM)
    [InlineData(64.0, 63.5, 120.0, true)]    // exact -1 beat edge
    [InlineData(64.0, 64.501, 120.0, false)] // 1 ms outside +1 beat edge
    [InlineData(64.0, 63.499, 120.0, false)] // 1 ms outside -1 beat edge
    [InlineData(60.0, 60.34, 174.0, true)]   // inside 1 beat at 174 BPM (0.3448 s)
    [InlineData(60.0, 60.35, 174.0, false)]  // outside 1 beat at 174 BPM
    public void HasAgreementWithinOneBeat_RespectsExactOneBeatEdge(
        double cueSeconds, double aiSeconds, double bpm, bool expected)
    {
        var ai = new List<CueDetrPoint> { new(0, aiSeconds, 0.9) };
        Assert.Equal(expected, CueDetrFusion.HasAgreementWithinOneBeat(cueSeconds, ai, bpm));
    }

    [Fact]
    public void ApplyAgreement_HandPlacedCues_AreNeverFlagged()
    {
        var ai = new List<CueDetrPoint> { new(0, 10.0, 0.95) };
        var cues = new List<OrbitCue>
        {
            new() { Name = "User Drop", Timestamp = 64.0, Role = CueRole.Drop, Source = CueSource.User },
            new() { Name = "Auto Drop (unconfirmed)", Timestamp = 64.0, Role = CueRole.Drop, Source = CueSource.Auto },
            new() { Name = "Auto Intro (agreed)", Timestamp = 10.2, Role = CueRole.Intro, Source = CueSource.Auto },
        };

        CueDetrFusion.ApplyAgreement(cues, ai, bpm: 120.0);

        Assert.Null(cues[0].AiAgreed);
        Assert.False(cues[0].NeedsCheck);

        Assert.Equal(false, cues[1].AiAgreed);
        Assert.True(cues[1].NeedsCheck);

        Assert.Equal(true, cues[2].AiAgreed);
        Assert.False(cues[2].NeedsCheck);
    }

    [Fact]
    public void HasUnconfirmedAutoDrop_TrueOnlyForUnconfirmedAutoDrops()
    {
        var featuresNoAi = new AudioFeaturesEntity { TrackUniqueHash = "t1", Bpm = 120f, CueDetrJson = null };
        var featuresAgreedAi = new AudioFeaturesEntity
        {
            TrackUniqueHash = "t1",
            Bpm = 120f,
            CueDetrJson = """{"model":"v1","points":[{"t":64.2,"s":0.9}]}"""
        };

        var autoDropOnly = new List<CuePointEntity>
        {
            new() { TrackUniqueHash = "t1", TimestampInSeconds = 64.0, Type = CuePointType.Drop, IsAutoGenerated = true },
        };
        var userDrop = new List<CuePointEntity>
        {
            new() { TrackUniqueHash = "t1", TimestampInSeconds = 64.0, Type = CuePointType.Drop, IsAutoGenerated = false },
        };

        Assert.True(CueDetrFusion.HasUnconfirmedAutoDrop(featuresNoAi, autoDropOnly));
        Assert.False(CueDetrFusion.HasUnconfirmedAutoDrop(featuresAgreedAi, autoDropOnly));
        Assert.False(CueDetrFusion.HasUnconfirmedAutoDrop(featuresNoAi, userDrop));
    }

    [Fact]
    public async Task CueForge_CheckTheseFirst_SortsDropsFirst_AndExcludesUserAndAgreedCues()
    {
        var cueService = new Mock<ICuePointService>();
        cueService.Setup(s => s.GetByTrackIdAsync("hash-cf1", It.IsAny<CancellationToken>()))
            .ReturnsAsync(new List<CuePointEntity>
            {
                new() { TrackUniqueHash = "hash-cf1", TimestampInSeconds = 8.0, Type = CuePointType.Intro, Label = "Intro", IsAutoGenerated = true },
                new() { TrackUniqueHash = "hash-cf1", TimestampInSeconds = 32.0, Type = CuePointType.Breakdown, Label = "Breakdown", IsAutoGenerated = true },
                new() { TrackUniqueHash = "hash-cf1", TimestampInSeconds = 64.0, Type = CuePointType.Drop, Label = "Drop 1", IsAutoGenerated = true },
                new() { TrackUniqueHash = "hash-cf1", TimestampInSeconds = 96.0, Type = CuePointType.Drop, Label = "User Drop", IsAutoGenerated = false },
            });

        var libraryService = new Mock<ILibraryService>();
        libraryService.Setup(s => s.GetAudioFeaturesByHashAsync("hash-cf1"))
            .ReturnsAsync(new AudioFeaturesEntity
            {
                TrackUniqueHash = "hash-cf1",
                Bpm = 120f,
                TrackDuration = 180f,
                // Agrees ONLY with Breakdown at 32.0s; Intro (8.0s) and Drop 1 (64.0s) are unconfirmed
                CueDetrJson = """{"model":"v1","points":[{"t":32.2,"s":0.92}]}"""
            });
        libraryService.Setup(s => s.GetPhrasesByHashAsync("hash-cf1"))
            .ReturnsAsync(new List<TrackPhraseEntity>());

        var transport = new Mock<ICueForgeTransport>();
        transport.SetupGet(t => t.CurrentTrackChanged).Returns(System.Reactive.Linq.Observable.Never<CueForgeTrackRef>());
        transport.SetupGet(t => t.PositionChanged).Returns(System.Reactive.Linq.Observable.Never<(double, double)>());
        transport.SetupGet(t => t.IsPlayingChanged).Returns(System.Reactive.Linq.Observable.Never<bool>());
        transport.SetupGet(t => t.IncomingMixChanged).Returns(System.Reactive.Linq.Observable.Never<CueForgeIncomingMixInfo>());

        using var vm = new CueForgeViewModel(
            cueService.Object,
            transport.Object,
            new AppConfig(),
            libraryService: libraryService.Object,
            ui: a => { a(); return Task.CompletedTask; });

        await vm.LoadTrackAsync("hash-cf1", "Test Track", "Test Artist");

        Assert.True(vm.HasCuesToCheckFirst);
        Assert.Equal(2, vm.CuesToCheckFirst.Count);
        // Drop 1 must appear BEFORE Intro despite later timestamp!
        Assert.Equal("Drop 1", vm.CuesToCheckFirst[0].Name);
        Assert.Equal("Intro", vm.CuesToCheckFirst[1].Name);
        // Breakdown (agreed) and User Drop (hand-placed) must NOT be in CuesToCheckFirst
        Assert.DoesNotContain(vm.CuesToCheckFirst, c => c.Name == "Breakdown");
        Assert.DoesNotContain(vm.CuesToCheckFirst, c => c.Name == "User Drop");
    }

    [Fact]
    public async Task PrepForMix_WithCueDetr_ReportsProgress_AndIsCancellable()
    {
        using var scope = new FreshDatabaseScope();
        var factory = new TestDbContextFactory();
        await using (var db = await factory.CreateDbContextAsync())
        {
            await db.Database.EnsureCreatedAsync();
        }

        var playlistId = Guid.NewGuid();
        await using (var db = await factory.CreateDbContextAsync())
        {
            for (int i = 0; i < 3; i++)
            {
                string hash = $"detr-{i}";
                db.PlaylistTracks.Add(new PlaylistTrackEntity
                {
                    Id = Guid.NewGuid(),
                    PlaylistId = playlistId,
                    TrackUniqueHash = hash,
                    Artist = "Artist",
                    Title = $"Track {i}",
                    ResolvedFilePath = $"C:/fake/{hash}.mp3",
                    Status = TrackStatus.Downloaded,
                    SortOrder = i,
                });
                db.AudioFeatures.Add(new AudioFeaturesEntity
                {
                    TrackUniqueHash = hash,
                    Bpm = 128f,
                    BeatGridJson = "[0.0,0.468]",
                    LoudnessLUFS = -8.5f,
                    WaveformBlob = new byte[] { 1, 2, 3, 4 },
                    StructuralVersion = 1,
                    TrackDuration = 200f,
                    CueDetrJson = null, // missing CUE-DETR cache!
                });
                db.CuePoints.AddRange(
                    new CuePointEntity { TrackUniqueHash = hash, TimestampInSeconds = 8.0, Type = CuePointType.Intro, Label = "Intro", IsAutoGenerated = true },
                    new CuePointEntity { TrackUniqueHash = hash, TimestampInSeconds = 180.0, Type = CuePointType.Outro, Label = "Outro", IsAutoGenerated = true });
            }
            await db.SaveChangesAsync();
        }

        using var cts = new CancellationTokenSource();
        var cueDetrCalls = new List<string>();
        var progressReports = new List<PlaylistPrepProgress>();
        var progress = new SyncProgress<PlaylistPrepProgress>(p => progressReports.Add(p));

        var svc = new PlaylistPrepService(
            factory,
            audioAnalysisOverride: (_, _, _, _) => Task.FromResult(true),
            structureAndCuesOverride: (_, _, _) => Task.FromResult(true),
            eligibilityOverride: _ => true,
            cueDetrOverride: (hash, _, ct) =>
            {
                ct.ThrowIfCancellationRequested();
                cueDetrCalls.Add(hash);
                if (cueDetrCalls.Count == 1) cts.Cancel(); // cancel right after first track
                return Task.FromResult(true);
            },
            runCueDetrSettingOverride: () => true);

        var result = await svc.PrepareAsync(playlistId, progress, cts.Token);

        Assert.True(result.WasCancelled);
        Assert.Single(cueDetrCalls);
        Assert.Contains(progressReports, p => p.StatusText.StartsWith("CUE-DETR ", StringComparison.Ordinal));
    }

    [Fact]
    public async Task ReadinessList_SortsTracksWithUnconfirmedDropsFirst()
    {
        using var scope = new FreshDatabaseScope();
        var factory = new TestDbContextFactory();
        await using (var db = await factory.CreateDbContextAsync())
        {
            await db.Database.EnsureCreatedAsync();
        }

        var playlistId = Guid.NewGuid();
        await using (var db = await factory.CreateDbContextAsync())
        {
            // Track 0 (earlier SortOrder): missing LUFS, NO unconfirmed drop
            db.PlaylistTracks.Add(new PlaylistTrackEntity
            {
                Id = Guid.NewGuid(),
                PlaylistId = playlistId,
                TrackUniqueHash = "no-drop-issue",
                Artist = "A",
                Title = "No Drop Issue",
                ResolvedFilePath = "C:/fake/a.mp3",
                Status = TrackStatus.Downloaded,
                SortOrder = 0,
            });
            db.AudioFeatures.Add(new AudioFeaturesEntity
            {
                TrackUniqueHash = "no-drop-issue",
                Bpm = 128f,
                BeatGridJson = "[0.0,0.468]",
                LoudnessLUFS = 0, // unready
            });

            // Track 1 (later SortOrder): missing LUFS AND has an unconfirmed auto drop!
            db.PlaylistTracks.Add(new PlaylistTrackEntity
            {
                Id = Guid.NewGuid(),
                PlaylistId = playlistId,
                TrackUniqueHash = "unconfirmed-drop",
                Artist = "B",
                Title = "Unconfirmed Drop Track",
                ResolvedFilePath = "C:/fake/b.mp3",
                Status = TrackStatus.Downloaded,
                SortOrder = 1,
            });
            db.AudioFeatures.Add(new AudioFeaturesEntity
            {
                TrackUniqueHash = "unconfirmed-drop",
                Bpm = 128f,
                BeatGridJson = "[0.0,0.468]",
                LoudnessLUFS = 0, // unready
                CueDetrJson = null,
            });
            db.CuePoints.Add(new CuePointEntity
            {
                TrackUniqueHash = "unconfirmed-drop",
                TimestampInSeconds = 64.0,
                Type = CuePointType.Drop,
                Label = "Drop 1",
                IsAutoGenerated = true,
            });
            await db.SaveChangesAsync();
        }

        var vm = new PlaylistReadinessViewModel(factory);
        await vm.RefreshAsync(playlistId, "Test Playlist");

        Assert.Equal(2, vm.UnreadyTracks.Count);
        Assert.Equal("unconfirmed-drop", vm.UnreadyTracks[0].TrackUniqueHash);
        Assert.True(vm.UnreadyTracks[0].HasUnconfirmedDrop);
        Assert.Equal("no-drop-issue", vm.UnreadyTracks[1].TrackUniqueHash);
        Assert.False(vm.UnreadyTracks[1].HasUnconfirmedDrop);
    }

    private sealed class SyncProgress<T>(Action<T> onReport) : IProgress<T>
    {
        public void Report(T value) => onReport(value);
    }
