using System.Reactive.Linq;
using System.Text.Json;
using Moq;
using SLSKDONET.Configuration;
using SLSKDONET.Data.Entities;
using SLSKDONET.Services;
using SLSKDONET.ViewModels;
using SLSKDONET.Views.Avalonia;

/// <summary>Cue Forge with a synthetic 174 BPM drum &amp; bass track: two drops, a breakdown, countdown cues.</summary>
static class CueForgeSnapshots
{
    const string Hash = "snapshot-dnb";
    const double Bpm = 174;
    const double Duration = 300;

    public static void Render(string output, int width, int height, Action<Avalonia.Controls.Control, Task, string?, int, int, Action?, string?> snap)
    {
        // Empty: nothing loaded.
        var empty = Create();
        snap(new CueForgePage(empty), Task.CompletedTask, Path.Combine(output, "cueforge-1-empty.png"), width, height, null, null);

        // A track loaded.
        var vm = Create();
        snap(new CueForgePage(vm), vm.LoadTrackAsync(Hash, "Afterglow (Original Mix)", "Wilkinson"),
            Path.Combine(output, $"cueforge-2-loaded-{width}.png"), width, height, null, null);
    }

    static CueForgeViewModel Create()
    {
        var cues = new Mock<ICuePointService>();
        cues.Setup(s => s.GetByTrackIdAsync(Hash, It.IsAny<CancellationToken>())).ReturnsAsync(Cues());

        var library = new Mock<ILibraryService> { DefaultValue = DefaultValue.Mock };
        library.Setup(s => s.GetAudioFeaturesByHashAsync(Hash)).ReturnsAsync(Features());
        library.Setup(s => s.GetPhrasesByHashAsync(Hash)).ReturnsAsync(new List<TrackPhraseEntity>());

        var transport = new Mock<ICueForgeTransport> { DefaultValue = DefaultValue.Mock };
        transport.SetupGet(t => t.CurrentTrackChanged).Returns(Observable.Never<CueForgeTrackRef>());
        transport.SetupGet(t => t.PositionChanged).Returns(Observable.Never<(double, double)>());
        transport.SetupGet(t => t.IsPlayingChanged).Returns(Observable.Never<bool>());
        transport.SetupGet(t => t.IncomingMixChanged).Returns(Observable.Never<CueForgeIncomingMixInfo>());

        return new CueForgeViewModel(cues.Object, transport.Object, new AppConfig(),
            libraryService: library.Object, ui: a => { a(); return Task.CompletedTask; });
    }

    static double Bar => 4 * 60 / Bpm;

    static List<CuePointEntity> Cues()
    {
        double drop1 = 64 * Bar, drop2 = drop1 + 64 * Bar + 32 * Bar;
        CuePointEntity C(double t, CuePointType type, string label, string color, int slot = -1) =>
            new() { TrackUniqueHash = Hash, TimestampInSeconds = t, Type = type, Label = label, Color = color, SlotIndex = slot, IsAutoGenerated = true };
        return new()
        {
            C(16 * Bar, CuePointType.Intro, "[IN]", "#00FF00", 0),
            C(drop1 - 16 * Bar, CuePointType.Build, "[IN -16]", "#FFA500"),
            C(drop1 - 8 * Bar, CuePointType.Build, "[IN -8]", "#FFA500"),
            C(drop1, CuePointType.Drop, "[DROP 1]", "#FF4500", 2),
            C(drop1 + 64 * Bar, CuePointType.Breakdown, "Breakdown", "#3399FF"),
            C(drop2 - 16 * Bar, CuePointType.Build, "[IN2 -16]", "#8800FF"),
            C(drop2, CuePointType.Drop, "[DROP 2]", "#00CCFF", 5),
            C(drop2 + 32 * Bar, CuePointType.Outro, "[OUT]", "#FF0000", 6),
        };
    }

    static AudioFeaturesEntity Features()
    {
        const int n = 2400;
        var blob = new byte[n * 3];
        var rng = new Random(7);
        double drop1 = 64 * Bar, breakdown = drop1 + 64 * Bar, drop2 = breakdown + 32 * Bar, outro = drop2 + 64 * Bar;
        var energy = new List<float>();
        for (int i = 0; i < n; i++)
        {
            double t = i * Duration / n;
            double level = t < 16 * Bar ? 0.35 : t < drop1 - 16 * Bar ? 0.5 : t < drop1 ? 0.45 + 0.3 * (t - (drop1 - 16 * Bar)) / (16 * Bar)
                : t < breakdown ? 0.95 : t < drop2 - 8 * Bar ? 0.3 : t < drop2 ? 0.6 : t < outro ? 0.95 : Math.Max(0.1, 0.6 - (t - outro) / 60);
            double beat = (t % (60 / Bpm)) < 0.06 ? 1.0 : 0.75;
            double jitter = 0.85 + rng.NextDouble() * 0.15;
            bool bassless = t >= breakdown && t < drop2 - 8 * Bar;
            blob[i] = (byte)Math.Clamp(255 * level * beat * jitter * (bassless ? 0.25 : 1.0), 0, 255);
            blob[n + i] = (byte)Math.Clamp(255 * level * 0.7 * jitter, 0, 255);
            blob[2 * n + i] = (byte)Math.Clamp(255 * level * 0.45 * (0.7 + rng.NextDouble() * 0.3), 0, 255);
            if (i % 24 == 0) energy.Add((float)level);
        }
        var beats = new List<float>();
        for (double t = 0.12; t < Duration; t += 60 / Bpm) beats.Add((float)t);
        return new AudioFeaturesEntity
        {
            TrackUniqueHash = Hash,
            Bpm = (float)Bpm,
            TrackDuration = (float)Duration,
            DownbeatOffsetSeconds = 0.12f,
            Key = "8A",
            WaveformBlob = blob,
            WaveformBlobSampleCount = n,
            AnalysisVersion = SLSKDONET.Services.AudioAnalysis.WaveformExtractionService.CurrentWaveformVersion,
            EnergyCurveJson = JsonSerializer.Serialize(energy),
            BeatGridJson = JsonSerializer.Serialize(beats),
            DetectedSubGenre = "Liquid Drum & Bass",
            EnergyScore = 7,
        };
    }
}
