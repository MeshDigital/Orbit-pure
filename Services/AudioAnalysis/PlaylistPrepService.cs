namespace SLSKDONET.Services.AudioAnalysis;

/// <summary>
/// Progress snapshot reported by <see cref="IPlaylistPrepService"/> while preparing a playlist for mixing.
/// </summary>
public sealed record PlaylistPrepProgress(
    int Completed,
    int Total,
    int Prepared,
    int Skipped,
    int Failed,
    string CurrentTrackLabel,
    string StatusText)
{
    public int Percent => Total > 0 ? (int)Math.Round(Completed * 100.0 / Total) : 0;
}

/// <summary>
/// Summary returned when <see cref="IPlaylistPrepService.PrepareAsync"/> or
/// <see cref="IPlaylistPrepService.PrepareTracksAsync"/> finishes or is cancelled.
/// </summary>
public sealed record PlaylistPrepResult(
    int TotalEligible,
    int Prepared,
    int Skipped,
    int Failed,
    int Unavailable,
    bool WasCancelled,
    IReadOnlyList<string> Errors);

/// <summary>
/// Prepares every eligible track in a playlist for clean DJ mixing by chaining only the missing
/// analysis steps (full audio analysis where missing, beat grid, integrated loudness, structural
/// phrase map, and auto cues). Already-ready tracks are skipped, and user-placed or imported cues
/// (<see cref="CuePointEntity.IsAutoGenerated"/> == false) are never modified or deleted.
/// </summary>
public interface IPlaylistPrepService
{
    Task<PlaylistPrepResult> PrepareAsync(
        Guid playlistId,
        IProgress<PlaylistPrepProgress>? progress = null,
        CancellationToken cancellationToken = default);

    Task<PlaylistPrepResult> PrepareTracksAsync(
        IReadOnlyList<PlaylistTrack> tracks,
        IProgress<PlaylistPrepProgress>? progress = null,
        CancellationToken cancellationToken = default);
}

/// <summary>
/// Singleton implementation of <see cref="IPlaylistPrepService"/>. Constructor performs no I/O so it
/// can never poison the DI container.
/// </summary>
public sealed class PlaylistPrepService : IPlaylistPrepService
{
    private readonly IDbContextFactory<AppDbContext> _dbFactory;
    private readonly IAudioAnalysisService? _audioAnalysisService;
    private readonly AnalyzeTrackStructureJob? _analyzeJob;
    private readonly CueDetrCueService? _cueDetrCueService;
    private readonly IEventBus? _eventBus;
    private readonly ConfigManager? _configManager;
    private readonly ILogger<PlaylistPrepService>? _logger;

    private readonly Func<string, string, AnalysisEngine, CancellationToken, Task<bool>>? _audioAnalysisOverride;
    private readonly Func<string, bool, CancellationToken, Task<bool>>? _structureAndCuesOverride;
    private readonly Func<string, string, CancellationToken, Task<bool>>? _cueDetrOverride;
    private readonly Func<bool>? _runCueDetrSettingOverride;
    private readonly Func<PlaylistTrack, bool>? _eligibilityOverride;

    public PlaylistPrepService(
        IDbContextFactory<AppDbContext> dbFactory,
        IAudioAnalysisService? audioAnalysisService = null,
        AnalyzeTrackStructureJob? analyzeJob = null,
        IEventBus? eventBus = null,
        ConfigManager? configManager = null,
        ILogger<PlaylistPrepService>? logger = null,
        CueDetrCueService? cueDetrCueService = null)
    {
        _dbFactory = dbFactory ?? throw new ArgumentNullException(nameof(dbFactory));
        _audioAnalysisService = audioAnalysisService;
        _analyzeJob = analyzeJob;
        _cueDetrCueService = cueDetrCueService;
        _eventBus = eventBus;
        _configManager = configManager;
        _logger = logger;
    }

    internal PlaylistPrepService(
        IDbContextFactory<AppDbContext> dbFactory,
        Func<string, string, AnalysisEngine, CancellationToken, Task<bool>> audioAnalysisOverride,
        Func<string, bool, CancellationToken, Task<bool>> structureAndCuesOverride,
        Func<PlaylistTrack, bool>? eligibilityOverride = null,
        IEventBus? eventBus = null,
        ILogger<PlaylistPrepService>? logger = null,
        Func<string, string, CancellationToken, Task<bool>>? cueDetrOverride = null,
        Func<bool>? runCueDetrSettingOverride = null)
    {
        _dbFactory = dbFactory ?? throw new ArgumentNullException(nameof(dbFactory));
        _audioAnalysisOverride = audioAnalysisOverride ?? throw new ArgumentNullException(nameof(audioAnalysisOverride));
        _structureAndCuesOverride = structureAndCuesOverride ?? throw new ArgumentNullException(nameof(structureAndCuesOverride));
        _cueDetrOverride = cueDetrOverride;
        _runCueDetrSettingOverride = runCueDetrSettingOverride;
        _eligibilityOverride = eligibilityOverride;
        _eventBus = eventBus;
        _logger = logger;
    }

    public async Task<PlaylistPrepResult> PrepareAsync(
        Guid playlistId,
        IProgress<PlaylistPrepProgress>? progress = null,
        CancellationToken cancellationToken = default)
    {
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken).ConfigureAwait(false);
        var entities = await db.PlaylistTracks
            .AsNoTracking()
            .Where(t => t.PlaylistId == playlistId)
            .OrderBy(t => t.SortOrder)
            .ToListAsync(cancellationToken)
            .ConfigureAwait(false);

        var tracks = entities.Select(e => new PlaylistTrack
        {
            Id = e.Id,
            PlaylistId = e.PlaylistId,
            Artist = e.Artist,
            Title = e.Title,
            Album = e.Album,
            TrackUniqueHash = e.TrackUniqueHash ?? string.Empty,
            ResolvedFilePath = e.ResolvedFilePath ?? string.Empty,
            Status = e.Status,
            SortOrder = e.SortOrder,
        }).ToList();

        return await PrepareTracksAsync(tracks, progress, cancellationToken).ConfigureAwait(false);
    }

    public async Task<PlaylistPrepResult> PrepareTracksAsync(
        IReadOnlyList<PlaylistTrack> tracks,
        IProgress<PlaylistPrepProgress>? progress = null,
        CancellationToken cancellationToken = default)
    {
        if (tracks is null || tracks.Count == 0)
        {
            return new PlaylistPrepResult(0, 0, 0, 0, 0, false, Array.Empty<string>());
        }

        var eligible = new List<PlaylistTrack>(tracks.Count);
        var seenHashes = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        int unavailable = 0;

        foreach (var track in tracks)
        {
            if (string.IsNullOrWhiteSpace(track.TrackUniqueHash) || !IsLocalFileEligible(track))
            {
                unavailable++;
                continue;
            }

            if (seenHashes.Add(track.TrackUniqueHash))
            {
                eligible.Add(track);
            }
        }

        if (eligible.Count == 0)
        {
            return new PlaylistPrepResult(0, 0, 0, 0, unavailable, false, Array.Empty<string>());
        }

        int total = eligible.Count;
        int completed = 0;
        int prepared = 0;
        int skipped = 0;
        int failed = 0;
        bool wasCancelled = false;
        var errors = new List<string>();

        foreach (var track in eligible)
        {
            if (cancellationToken.IsCancellationRequested)
            {
                wasCancelled = true;
                break;
            }

            string hash = track.TrackUniqueHash;
            string label = FormatTrackLabel(track);

            try
            {
                var (features, cues) = await LoadTrackStateAsync(hash, cancellationToken).ConfigureAwait(false);
                var readiness = TrackMixReadinessEvaluator.Evaluate(features, cues);
                bool needsCueDetr = ShouldRunCueDetr() && string.IsNullOrWhiteSpace(features?.CueDetrJson);

                if (readiness.IsReady && !needsCueDetr)
                {
                    skipped++;
                    completed++;
                    progress?.Report(new PlaylistPrepProgress(
                        completed, total, prepared, skipped, failed, label,
                        $"Skipped {skipped} · {completed}/{total}"));
                    continue;
                }

                progress?.Report(new PlaylistPrepProgress(
                    completed, total, prepared, skipped, failed, label,
                    $"Prepping {label}… ({completed + 1}/{total})"));

                bool ranAnyStep = false;
                bool stepFailed = false;

                // Step 1: Audio analysis (full pipeline if never analysed, or only missing audio engines)
                var missingEngines = features is null
                    ? AnalysisEngine.Pipeline
                    : readiness.MissingAudioEngines;

                if (missingEngines != AnalysisEngine.None)
                {
                    ranAnyStep = true;
                    bool audioOk = await RunAudioAnalysisAsync(
                        track.ResolvedFilePath, hash, missingEngines, cancellationToken).ConfigureAwait(false);

                    if (!audioOk)
                    {
                        stepFailed = true;
                        errors.Add($"{label}: audio analysis returned no result.");
                    }
                    else
                    {
                        // Refresh features after audio analysis so the structure/cue step sees the new BPM/grid/signals.
                        (features, cues) = await LoadTrackStateAsync(hash, cancellationToken).ConfigureAwait(false);
                        readiness = TrackMixReadinessEvaluator.Evaluate(features, cues);
                    }
                }

                if (cancellationToken.IsCancellationRequested)
                {
                    wasCancelled = true;
                    break;
                }

                // Step 2: Structural analysis + auto-cues (preserves every IsAutoGenerated=false cue)
                if (!stepFailed && (readiness.NeedsCues || cues.Count == 0))
                {
                    ranAnyStep = true;
                    bool needsStructure = !readiness.HasStructure;
                    bool cuesOk = await RunStructureAndCuesAsync(hash, needsStructure, cancellationToken)
                        .ConfigureAwait(false);

                    if (!cuesOk)
                    {
                        stepFailed = true;
                        errors.Add($"{label}: cue detection produced no cues.");
                    }
                }

                // Step 3 (CF1 #603): Optional CUE-DETR AI cue check for tracks without cached CueDetrJson
                if (!stepFailed && needsCueDetr)
                {
                    if (cancellationToken.IsCancellationRequested)
                    {
                        wasCancelled = true;
                        break;
                    }
                    ranAnyStep = true;
                    progress?.Report(new PlaylistPrepProgress(
                        completed, total, prepared, skipped, failed, label,
                        $"CUE-DETR {label}… ({completed + 1}/{total})"));

                    await RunCueDetrAsync(hash, track.ResolvedFilePath, cancellationToken).ConfigureAwait(false);
                }

                if (stepFailed)
                {
                    failed++;
                }
                else if (ranAnyStep)
                {
                    prepared++;
                    _eventBus?.Publish(new TrackAnalysisUpdatedEvent(hash, DateTime.UtcNow));
                }
                else
                {
                    skipped++;
                }
            }
            catch (OperationCanceledException)
            {
                wasCancelled = true;
                break;
            }
            catch (Exception ex)
            {
                failed++;
                string msg = $"{label}: {ex.Message}";
                errors.Add(msg);
                _logger?.LogWarning(ex, "[PlaylistPrep] Failed preparing track {Hash} ({Label})", hash, label);
            }

            completed++;
            progress?.Report(new PlaylistPrepProgress(
                completed, total, prepared, skipped, failed, label,
                $"Prepped {prepared} · Skipped {skipped} · {completed}/{total}"));
        }

        return new PlaylistPrepResult(
            TotalEligible: total,
            Prepared: prepared,
            Skipped: skipped,
            Failed: failed,
            Unavailable: unavailable,
            WasCancelled: wasCancelled,
            Errors: errors);
    }

    private bool IsLocalFileEligible(PlaylistTrack track)
    {
        if (_eligibilityOverride is not null)
            return _eligibilityOverride(track);

        return track != null
            && track.Status == TrackStatus.Downloaded
            && !string.IsNullOrWhiteSpace(track.ResolvedFilePath)
            && File.Exists(track.ResolvedFilePath)
            && !string.IsNullOrWhiteSpace(track.TrackUniqueHash);
    }

    private async Task<(AudioFeaturesEntity? Features, List<CuePointEntity> Cues)> LoadTrackStateAsync(
        string trackUniqueHash,
        CancellationToken ct)
    {
        await using var db = await _dbFactory.CreateDbContextAsync(ct).ConfigureAwait(false);
        var features = await db.AudioFeatures
            .AsNoTracking()
            .FirstOrDefaultAsync(f => f.TrackUniqueHash == trackUniqueHash, ct)
            .ConfigureAwait(false);

        var cues = await db.CuePoints
            .AsNoTracking()
            .Where(c => c.TrackUniqueHash == trackUniqueHash)
            .OrderBy(c => c.TimestampInSeconds)
            .ToListAsync(ct)
            .ConfigureAwait(false);

        return (features, cues);
    }

    private async Task<bool> RunAudioAnalysisAsync(
        string filePath,
        string trackUniqueHash,
        AnalysisEngine engines,
        CancellationToken ct)
    {
        if (_audioAnalysisOverride is not null)
            return await _audioAnalysisOverride(filePath, trackUniqueHash, engines, ct).ConfigureAwait(false);

        if (_audioAnalysisService is null)
            return false;

        var audioEngine = AnalysisAudioEngineExtensions.ParseAudioEngine(_configManager?.GetCurrent().AnalysisAudioEngine);
        var result = await _audioAnalysisService.AnalyzeFileAsync(
            filePath,
            trackUniqueHash,
            engines: engines,
            audioEngine: audioEngine,
            cancellationToken: ct).ConfigureAwait(false);

        return result is not null;
    }

    private async Task<bool> RunStructureAndCuesAsync(
        string trackUniqueHash,
        bool needsStructure,
        CancellationToken ct)
    {
        if (_structureAndCuesOverride is not null)
            return await _structureAndCuesOverride(trackUniqueHash, needsStructure, ct).ConfigureAwait(false);

        if (_analyzeJob is null)
            return false;

        if (needsStructure)
        {
            await _analyzeJob.ExecuteAsync(trackUniqueHash, ct, generateCues: true).ConfigureAwait(false);
            return true;
        }

        return await _analyzeJob.RegenerateCuesOnlyAsync(trackUniqueHash, ct).ConfigureAwait(false);
    }

    private bool ShouldRunCueDetr()
    {
        if (_runCueDetrSettingOverride is not null)
            return _runCueDetrSettingOverride();
        if (_configManager?.GetCurrent().PrepForMixRunCueDetr != true)
            return false;
        return _cueDetrOverride is not null || (_cueDetrCueService?.IsModelAvailable ?? false);
    }

    private async Task<bool> RunCueDetrAsync(string trackUniqueHash, string filePath, CancellationToken ct)
    {
        if (_cueDetrOverride is not null)
            return await _cueDetrOverride(trackUniqueHash, filePath, ct).ConfigureAwait(false);
        if (_cueDetrCueService is null)
            return false;
        return await _cueDetrCueService.EnsureCachedAsync(trackUniqueHash, filePath, ct).ConfigureAwait(false);
    }

    private static string FormatTrackLabel(PlaylistTrack track)
    {
        if (!string.IsNullOrWhiteSpace(track.Title)) return track.Title;
        var hash = track.TrackUniqueHash;
        return hash.Length > 8 ? hash[..8] : hash;
    }
}
