using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using SLSKDONET.Data;
using SLSKDONET.Data.Entities;
using SLSKDONET.Engine.Cueing;
using SLSKDONET.Models;
using SLSKDONET.Views;

namespace SLSKDONET.Services.AudioAnalysis;

/// <summary>
/// One-time background repair of already-stored auto cues after two generator changes:
/// <list type="number">
/// <item>A second drop found in the last 16 bars used to be clamped to the end of the track, giving
/// [DROP 2] with countdowns into the outro and an [OUT] glued to it (5% of one real library). Those
/// tracks get their auto cues regenerated with the fixed generator.</item>
/// <item>Drop 2's countdowns are now named [IN2 -16] / [IN2 -8] so a CDJ never shows two identical
/// labels. On every other track with an auto Drop 2, the auto countdowns are just renamed.</item>
/// </list>
/// Only auto cues change (cues you placed or edited are never touched), tracks with drops you placed
/// yourself are skipped, a consistent backup of the library is written first, and a marker file
/// makes the pass run once. Same pattern as <see cref="BeatGridRecomputeService"/>.
/// </summary>
public sealed class CueLayoutRepairService
{
    private const string PassName = "cue-layout-v2";
    private static readonly TimeSpan StartDelay = TimeSpan.FromSeconds(90);

    private readonly ILogger<CueLayoutRepairService> _logger;
    private readonly IEventBus? _eventBus;

    public CueLayoutRepairService(ILogger<CueLayoutRepairService> logger, AnalyzeTrackStructureJob? cueJob = null, IEventBus? eventBus = null)
    {
        _logger = logger;
        _eventBus = eventBus;
        Regenerate = cueJob == null
            ? (_, _) => Task.FromResult(false)
            : (hash, ct) => cueJob.RegenerateCuesOnlyAsync(hash, ct);
    }

    /// <summary>Regenerates one track's auto cues; tests replace it.</summary>
    internal Func<string, CancellationToken, Task<bool>> Regenerate { get; set; }

    /// <summary>Holds the backup and the run-once marker; tests point it at a temp folder.</summary>
    internal string DataDirectory { get; set; } = Path.Combine(OrbitPaths.RoamingRoot, "ORBIT", "Backups");

    /// <summary>Tests limit the pass to their own tracks (the test database is shared).</summary>
    internal IReadOnlyCollection<string>? OnlyTracks { get; set; }

    private string MarkerPath => Path.Combine(DataDirectory, $"{PassName}.done");

    /// <summary>Starts the pass in the background if it hasn't run yet. Never throws.</summary>
    public void StartIfPending(CancellationToken ct = default)
    {
        if (File.Exists(MarkerPath)) return;
        _ = Task.Run(async () =>
        {
            try
            {
                await Task.Delay(StartDelay, ct).ConfigureAwait(false); // after the beat-grid pass and startup DB traffic
                await RunAsync(ct).ConfigureAwait(false);
            }
            catch (OperationCanceledException) { }
            catch (Exception ex)
            {
                _logger.LogError(ex, "[CueLayoutRepair] Pass failed; it will retry on next launch.");
            }
        }, ct);
    }

    public async Task<CueLayoutRepairSummary> RunAsync(CancellationToken ct = default)
    {
        if (File.Exists(MarkerPath)) return CueLayoutRepairSummary.AlreadyDone;

        List<(string Hash, double Drop2, double Bpm, double Duration)> drop2s;
        HashSet<string> manualDrops;
        using (var db = new AppDbContext())
        {
            drop2s = (await (from c in db.CuePoints.AsNoTracking()
                             join f in db.AudioFeatures.AsNoTracking() on c.TrackUniqueHash equals f.TrackUniqueHash
                             where c.IsAutoGenerated && !c.IsLoop && c.Label == "[DROP 2]" && f.Bpm > 0 && f.TrackDuration > 0
                             select new { c.TrackUniqueHash, c.TimestampInSeconds, f.Bpm, f.TrackDuration })
                    .ToListAsync(ct).ConfigureAwait(false))
                .GroupBy(x => x.TrackUniqueHash)
                .Select(g => g.First())
                .Select(x => (x.TrackUniqueHash, x.TimestampInSeconds, (double)x.Bpm, x.TrackDuration))
                .ToList();
            // Drops you placed own the track: no auto cues are regenerated there.
            manualDrops = (await db.CuePoints.AsNoTracking()
                .Where(c => !c.IsAutoGenerated && c.Type == CuePointType.Drop)
                .Select(c => c.TrackUniqueHash).Distinct()
                .ToListAsync(ct).ConfigureAwait(false)).ToHashSet();
        }

        var candidates = drop2s.Where(t => !manualDrops.Contains(t.Hash) && (OnlyTracks == null || OnlyTracks.Contains(t.Hash))).ToList();
        var late = candidates.Where(t => t.Drop2 > t.Duration - 16 * (240.0 / t.Bpm)).ToList();
        var renameOnly = candidates.Except(late).ToList();

        if (candidates.Count == 0)
        {
            WriteMarker("nothing to repair");
            return new CueLayoutRepairSummary(0, 0, 0, 0);
        }

        string backup = BackupLibrary();
        _logger.LogInformation("[CueLayoutRepair] {Late} tracks with a Drop 2 in the last 16 bars, {Rename} to rename (backup: {Backup})",
            late.Count, renameOnly.Count, backup);

        int regenerated = 0, failed = 0;
        foreach (var t in late)
        {
            ct.ThrowIfCancellationRequested();
            if (await Regenerate(t.Hash, ct).ConfigureAwait(false)) regenerated++; else failed++;
        }

        int renamed = await RenameDrop2CountdownsAsync(renameOnly, ct).ConfigureAwait(false);

        var summary = new CueLayoutRepairSummary(regenerated, failed, renamed, renameOnly.Count);
        string text = $"{regenerated} tracks with a Drop 2 in the outro regenerated ({failed} failed), {renamed} Drop 2 countdowns renamed to [IN2 …] on {renameOnly.Count} tracks";
        _logger.LogInformation("[CueLayoutRepair] Done: {Summary}", text);
        WriteMarker(text);

        if (regenerated > 0 || renamed > 0)
            _eventBus?.Publish(new ToastRequestedEvent("Auto cues repaired",
                $"Fixed the second drop on {regenerated} tracks where it sat in the outro, and renamed Drop 2's countdowns to [IN2 …]. Your own cues were not changed.",
                NotificationType.Success, TimeSpan.FromSeconds(8)));
        return summary;
    }

    /// <summary>Auto "[IN -N]" cues sitting exactly N bars before the auto Drop 2 become "[IN2 -N]".</summary>
    private async Task<int> RenameDrop2CountdownsAsync(List<(string Hash, double Drop2, double Bpm, double Duration)> tracks, CancellationToken ct)
    {
        int renamed = 0;
        foreach (var batch in tracks.Chunk(200))
        {
            ct.ThrowIfCancellationRequested();
            var byHash = batch.ToDictionary(t => t.Hash);
            var hashes = byHash.Keys.ToList();
            using var db = new AppDbContext();
            var countdowns = await db.CuePoints
                .Where(c => hashes.Contains(c.TrackUniqueHash) && c.IsAutoGenerated && !c.IsLoop && c.Label != null && c.Label.StartsWith("[IN -"))
                .ToListAsync(ct).ConfigureAwait(false);
            foreach (var cue in countdowns)
            {
                var t = byHash[cue.TrackUniqueHash];
                if (DropCountdownCues.CountdownBars(cue.Label) is not { } n) continue;
                double bar = 240.0 / t.Bpm;
                if (Math.Abs(cue.TimestampInSeconds - Math.Max(0, t.Drop2 - n * bar)) > bar / 8) continue; // Drop 1's countdown
                cue.Label = DropCountdownCues.CountdownName(n, 2);
                renamed++;
            }
            await db.SaveChangesAsync(ct).ConfigureAwait(false);
        }
        return renamed;
    }

    private string BackupLibrary()
    {
        Directory.CreateDirectory(DataDirectory);
        string target = Path.Combine(DataDirectory, $"library.db.bak-{PassName}-{DateTime.Now:yyyyMMdd-HHmmss}");
        using var src = new SqliteConnection(new SqliteConnectionStringBuilder { DataSource = OrbitPaths.LibraryDbPath, Mode = SqliteOpenMode.ReadOnly }.ToString());
        using var dst = new SqliteConnection(new SqliteConnectionStringBuilder { DataSource = target }.ToString());
        src.Open();
        dst.Open();
        src.BackupDatabase(dst);
        SqliteConnection.ClearPool(dst); // release the backup file handle
        return target;
    }

    private void WriteMarker(string summary)
    {
        try
        {
            Directory.CreateDirectory(DataDirectory);
            File.WriteAllText(MarkerPath, $"{DateTime.UtcNow:O}\n{summary}\n");
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "[CueLayoutRepair] Could not write marker {Path}", MarkerPath);
        }
    }
}

public sealed record CueLayoutRepairSummary(int Regenerated, int Failed, int CountdownsRenamed, int TracksChecked)
{
    public static CueLayoutRepairSummary AlreadyDone { get; } = new(0, 0, 0, 0);
}
